/// thực tế không còn mở nữa"*. Đo lại được cả chuỗi: `projects-d8` sống trong
/// cửa sổ `ttys002` (mở từ 12:28:08); 16:41:16 Hà thoát CLI rồi gõ `claude` lại
/// **ngay trong cửa sổ ấy**; 16:42:33 hub mới nhận ra phiên cũ đi, hỏi "có tab
/// nào mang tty ấy không" → còn → nói *"cửa sổ terminal còn mở"*.
///
/// Câu ấy đúng chữ mà sai nghĩa: cửa sổ ấy KHÔNG nằm chờ ai, nó đã là phiên
/// khác. Người đọc đi tìm một cửa sổ bỏ không sẽ không thấy nó ở đâu — và đó là
/// cách một câu đúng-về-kỹ-thuật trở thành một câu nói dối.
///
/// `tty` là một con số **được dùng lại**: cùng một `ttys002` có thể là cửa sổ
/// cũ, cửa sổ mới, hay một cái xác (xem `keys::window_script`). Nên trước khi
/// hỏi Terminal, hãy hỏi ảnh chụp của chính mình: phiên nào đang ngồi ở tty ấy?
/// Thư mục làm việc của hubd — nơi launchd đặt nó (plist `WorkingDirectory`).
const HUBD_RUNTIME_DIR: &str = "~/Library/Application Support/hub";

/// Phiên này có phải máy móc của CHÍNH hub không (phép dò `/usage` 5 phút/lượt).
///
/// Đo 2026-08-12: `hub-67` · `cwd = /Users/hanguyen/Library/Application
/// Support/hub` · `host = detached` — đúng thư mục launchd cho hubd chạy, và
/// tiến trình con `claude -p "/usage"` thừa hưởng nó. Không phiên nào của người
/// nằm ở đấy: chủ máy mở `claude` từ `~/projects`.
///
/// Dùng để IM cái chuông (`watch::changes`), **không** để giấu khỏi danh sách.
pub fn is_hub_own_probe(s: &LiveSession) -> bool {
    is_hub_runtime_cwd(&s.cwd)
}

/// Cùng phép thử, nhưng hỏi từ SỔ (`watch::Mark::c`) — cần cho phiên đã rời
/// danh sách: lúc ấy không còn hàng `LiveSession` nào để hỏi, mà đó chính là
/// lượt sinh ra tin "đã tắt".
pub fn is_hub_runtime_cwd(cwd: &str) -> bool {
    !cwd.is_empty() && Path::new(cwd) == crate::config::expand_home(Path::new(HUBD_RUNTIME_DIR))
}

/// Phiên có đang ĐỨNG vì một lỗi API không — đọc từ CẤU TRÚC nhật ký.
///
/// 🔴 Bản đầu (2026-08-13, vài phút trước) quét chữ `"API Error"` trên từng
/// DÒNG THÔ của nhật ký, và nó kêu oan ngay lượt thật đầu tiên: bản ghi khớp
/// chính là **báo cáo của tôi** — một tin nhắn NÓI VỀ lỗi API. Tin gửi đi mang
/// nguyên 4 KB JSON làm "dòng lỗi". Hai cái sai chồng nhau: quét chữ trên một
/// tệp JSON, và không phân biệt *gặp lỗi* với *nhắc tới lỗi*.
///
/// Đo lại cho tử tế trên toàn bộ nhật ký của máy: **43 lỗi API thật đều mang
/// `isApiErrorMessage: true`** trên bản ghi `assistant` — một lá cờ máy đọc
/// được, không phải một chuỗi chữ. Ba ca dương tính giả đều là tin thường có
/// nhắc chữ ấy.
///
/// Và chỉ tính khi bản ghi assistant CUỐI CÙNG là lỗi: lỗi hai tiếng trước mà
/// phiên đã chạy tiếp thì nó không còn đứng vì lỗi nữa.
pub fn transcript_error(tail: &str) -> Option<String> {
    for line in tail.lines().rev() {
        let Ok(r) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        let Some(msg) = r.get("message") else { continue };
        if msg.get("role").and_then(Value::as_str) != Some("assistant") {
            continue;
        }
        // Bản ghi assistant cuối cùng quyết định — gặp cái không phải lỗi thì
        // phiên đã đi tiếp được rồi.
        if r.get("isApiErrorMessage").and_then(Value::as_bool) != Some(true) {
            return None;
        }
        let text = match msg.get("content") {
            Some(Value::String(t)) => t.clone(),
            Some(Value::Array(items)) => items
                .iter()
                .filter_map(|c| c.get("text").and_then(Value::as_str))
                .collect::<Vec<_>>()
                .join(" "),
            _ => String::new(),
        };
        let text = text.trim();
        return Some(if text.is_empty() {
            "lỗi API (nhật ký không kèm chữ)".to_string()
        } else {
            truncate(text, 200)
        });
    }
    None
}

