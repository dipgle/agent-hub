/// cùng luật với `open_drawer`, không biết thì đừng đoán.
fn strip_drawer(root: &Path, label: &str) -> String {
    let Some((first, rest)) = label.split_once('/') else {
        return label.to_string();
    };
    let dir = root.join(first);
    if dir.is_dir() && !crate::config::looks_like_project(&dir) {
        return rest.to_string();
    }
    label.to_string()
}

