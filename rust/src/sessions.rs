/// Một ô vuông màu ĐỨNG TRƯỚC tên dự án, cùng dự án thì cùng màu, mãi mãi.
///
/// 🔴 Hà 2026-08-14: *"Có cách nào đánh dấu màu vào tin nhận theo từng dự án để
/// dễ nhận biết"*. Telegram KHÔNG cho tô màu chữ tuỳ ý — bộ định dạng của nó là
/// đậm/nghiêng/gạch/khối mã/spoiler, không có thuộc tính màu (tài liệu Bot API,
/// mục *HTML style*). Thứ mang được màu vào một dòng chữ là **emoji**, nên nhãn
/// dự án đi kèm một ô vuông màu.
///
/// Màu phải suy TỪ TÊN chứ không phát theo thứ tự gặp: hub khởi động lại vài
/// lần một ngày, và một cái nhãn đổi màu sau mỗi lần khởi động thì tệ hơn không
/// có màu — người đọc học màu ấy rồi bị nó lừa. Băm tên là hàm thuần: cùng dự
/// án ⟹ cùng màu trên mọi tin, mọi máy, mọi lần chạy.
pub fn project_dot(folder: &str) -> &'static str {
    const DOTS: [&str; 8] = ["🟦", "🟩", "🟨", "🟧", "🟪", "🟫", "🟥", "⬜"];
    let key = folder.trim();
    if key.is_empty() {
        return "⬜";
    }
    // FNV-1a 32-bit: đủ tản cho tám ô, và viết gọn trong năm dòng — không kéo
    // thêm một crate băm vào đây cho một việc trang trí.
    let mut h: u32 = 0x811c_9dc5;
    for b in key.as_bytes() {
        h ^= *b as u32;
        h = h.wrapping_mul(0x0100_0193);
    }
    DOTS[(h % DOTS.len() as u32) as usize]
}


/// Cửa sổ của một phiên, lấy từ SỔ rồi bắt `ps` chứng thực — **không spawn
/// `claude`**.
///
/// 🔴 Hà 2026-08-12: *"tất cả các lệnh từ tele sao không xử lý luôn lại phải
/// chờ, rất lâu mới có phản hồi"* và *"chát từ tele toàn báo không thấy phiên"*.
/// Đo: `/type` **134 giây** rồi trả *"⚠ không thấy phiên"* — về đúng cái phiên
/// đang gõ dòng này. Cả hai là MỘT nguyên nhân: `/type`·`/key`·`/shot` đều gọi
/// `snapshot_cached`, mà một lượt dựng ảnh chụp là ba lần spawn `claude` (279
/// MB), và máy đang **swap 12,2/13,3 GB** ⟹ 15–92 giây một lượt, hết giờ thì
/// danh sách về THIẾU và "không có trong danh sách" bị đọc thành "không tồn
/// tại" (đúng lỗi `Look::Blind` ở một chỗ mới).
///
/// Vì sao sổ là đủ, mà trước đó tôi nói là KHÔNG đủ: một `tty` nhớ sẵn thì
/// không đủ (tty được dùng lại — cửa sổ ấy có thể đã là của phiên khác), nhưng
/// `tty` + `pid` thì đủ. `ps -o tty= -p <pid>` trả lời cả hai câu cùng lúc —
/// *tiến trình ấy còn sống không* và *nó còn ngồi đúng cửa sổ ấy không* — trong
/// vài mili giây. Phiên chết đi thì pid biến mất ⟹ hàm trả `None` ⟹ chỗ gọi rơi
/// về đường ảnh chụp, đúng như khi sổ chưa biết gì.
pub fn window_target_from_book(book_json: &str, id: &str) -> Option<LiveSession> {
    let book: std::collections::BTreeMap<String, crate::watch::Mark> =
        serde_json::from_str(book_json).ok()?;
    let mark = book.get(id)?;
    if mark.n.is_empty() || mark.i <= 0 || !is_real_tty(&mark.y) {
        return None;
    }
    let out = crate::exec::run(
        "ps",
        &["-o", "tty=", "-p", &mark.i.to_string()],
        crate::exec::RunOpts {
            timeout: Some(std::time::Duration::from_secs(5)),
            ..Default::default()
        },
    )
    .ok()?;
    let now_tty = out.stdout.trim();
    // `ps` in `ttys002`, sổ cũng giữ `ttys002` — nhưng đừng tin vào một chuỗi
    // rỗng: pid chết thì `ps` in ra không có gì, và "" == "" là một cái bẫy.
    if now_tty.is_empty() || now_tty.trim_start_matches("/dev/") != mark.y.trim_start_matches("/dev/")
    {
        return None;
    }
    Some(LiveSession {
        session_id: id.to_string(),
        name: mark.n.clone(),
        tty: mark.y.clone(),
        host: mark.o.clone(),
        folder: mark.d.clone(),
        account: mark.a.clone(),
        pid: mark.i,
        ..Default::default()
    })
}

/// `tty` này có phải một cửa sổ THẬT không.
///
/// 🔴 Đo 2026-08-12 22:59, trên đúng cái tin Hà đọc được: `⏹ hub-67 (033059d8)
/// đã tắt — cửa sổ ấy nay đang chạy phiên hub-ec.` Cả hai đều là phiên `claude
/// -p "/usage"` của CHÍNH hub, **không phiên nào có cửa sổ** — `ps` in `??` cho
/// tiến trình không có tty điều khiển. Mà `??` **không rỗng**, nên cửa
/// `tty.is_empty()` cho nó đi qua, rồi phép so "cùng tty" khớp `??` với `??` và
/// hub tuyên bố một cửa sổ không tồn tại đã bị chiếm.
///
/// Luật này đã được viết đúng ở `keys::window_of` và ở chỗ đặt nhãn
/// `terminal`/`detached` — ba chỗ, ba bản chép tay, và chỗ thứ tư quên. Nay một
/// chỗ, vì cái giá của bản chép thứ tư là một câu nói dối gửi thẳng ra điện thoại.
pub fn is_real_tty(tty: &str) -> bool {
    !(tty.is_empty() || tty == "??" || tty == "-")
}

pub fn window_taken_over<'a>(
    id: &str,
    tty: &str,
    live: &'a [LiveSession],
) -> Option<&'a LiveSession> {
    if !is_real_tty(tty) {
        return None;
    }
    live.iter()
        .find(|s| s.session_id != id && s.tty == tty && s.host != "dead")
}

/// `~/projects` → `-Users-hanguyen-projects`.
///
/// The rule the CLI uses for its transcript folders: every path separator
/// becomes a dash, including the leading one.
pub fn transcript_slug(cwd: &str) -> String {
    let trimmed = cwd.trim_end_matches('/');
    if trimmed.is_empty() {
        return "-".to_string();
    }
    trimmed.replace('/', "-")
}

pub fn transcript_path(root: &Path, cwd: &str, session_id: &str) -> PathBuf {
    root.join("projects")
        .join(transcript_slug(cwd))
        .join(format!("{session_id}.jsonl"))
}

/// Records that are bookkeeping, not conversation. Observed on real
/// transcripts: `pr-link`, `attachment`, `system`, `last-prompt`,
/// `file-history-snapshot`, `queue-operation`, `ai-title`, `mode`,
/// `permission-mode`. Reading the LAST record and calling it the state gets the
/// answer wrong for 5 of 14 live sessions, which is why this walks backwards.
fn is_conversation(kind: &str) -> bool {
    matches!(kind, "assistant" | "user")
}

/// Plain text out of a message record, whatever shape it arrived in.
fn text_of(record: &Value) -> Option<String> {
    let content = record.get("message")?.get("content")?;
    if let Some(s) = content.as_str() {
        return Some(s.trim().to_string()).filter(|s| !s.is_empty());
    }
    let joined = content
        .as_array()?
        .iter()
        .filter_map(|block| match block.get("type").and_then(|t| t.as_str()) {
            Some("text") => block
                .get("text")
                .and_then(|t| t.as_str())
                .map(str::to_string),
            // A turn that is only tool calls has no text; say what it was doing
            // rather than showing an empty row.
            Some("tool_use") => block
                .get("name")
                .and_then(|n| n.as_str())
                .map(|n| format!("[dùng {n}]")),
            _ => None,
        })
        .collect::<Vec<_>>()
        .join(" ");
    Some(joined.trim().to_string()).filter(|s| !s.is_empty())
}

