/// Where a live session is hosted, decided by the process behind its pid.
///
/// `claude agents` says "interactive" for a terminal window and for a session
/// the VS Code / Cursor extension is running — the extension ships its own
/// `claude` binary under `~/.vscode/extensions/…`, so the command PATH is what
/// separates them, not the process name. A pid that answers nothing at all is
/// a row the CLI still lists for a process that is gone: `"dead"`, so the phone
/// can show it as something to clean up rather than as work in progress.
/// `(host, tty)` — tty đi kèm vì đó là chìa ghép phiên với cửa sổ Terminal
/// (`keys::window_of`). Tính rồi vứt đi thì mỗi lần cần lại phải gọi `ps` lần
/// nữa, trên đúng con số vừa đọc xong.
fn host_of(pid: i64, kind: &str) -> (String, String) {
    if pid <= 0 {
        // Background rows come back with pid 0 once stopped; `claude agents`
        // keeps listing them. Both dead rows seen on 2026-08-09 were exactly
        // this — stopped on 08-07, still on the list two days later.
        return ("dead".into(), String::new());
    }
    let out = run(
        "ps",
        &["-p", &pid.to_string(), "-o", "tty=,command="],
        RunOpts {
            timeout: Some(Duration::from_secs(5)),
            ..Default::default()
        },
    );
    let cmd = match out {
        Ok(r) if r.code == Some(0) => r.stdout,
        // `ps` exits non-zero when the pid is gone — that is the answer, not a
        // failure. A spawn error is different: say "unknown" rather than
        // claiming a session is dead on the strength of a broken probe.
        Ok(_) => return ("dead".into(), String::new()),
        Err(e) => {
            logging::warn(
                "session_host_probe_failed",
                json!({ "pid": pid, "err": e.to_string() }),
            );
            return ("unknown".into(), String::new());
        }
    };
    // `ps -o tty=,command=` in ra tty rồi mới tới dòng lệnh; tty là từ đầu tiên.
    let (tty, cmd) = match cmd.trim_start().split_once(char::is_whitespace) {
        Some((t, rest)) => (t, rest),
        None => ("??", cmd.as_str()),
    };
    (classify_host(cmd, kind, tty).to_string(), tty.to_string())
}

/// The half of `host_of` that is a decision rather than a probe.
///
/// Split out so it can be tested: the editor branch is the one the phone acts
/// on — those rows are hidden — and on a machine with no editor session open
/// there is no way to exercise it through the UI. `host_of` still owns the
/// `ps` call and the pid-is-gone answer; this owns only "given this command
/// line, whose session is it".
pub fn classify_host(cmd: &str, kind: &str, tty: &str) -> &'static str {
    // A background session hub started is `--bg`, never an editor's, whatever
    // binary is on the path — the kind is the stronger signal, so it wins.
    if kind == "background" {
        return "background";
    }
    // The extension ships its own `claude` under the editor's extension dir, so
    // the PATH is what separates it from a terminal — the process name is
    // `claude` in both cases.
    if cmd.contains("/.vscode") || cmd.contains("/.cursor") || cmd.contains("Cursor.app") {
        return "editor";
    }
    // "terminal" phải CÓ NGHĨA LÀ terminal.
    //
    // Hà hỏi 2026-08-09: *"danh sách phiên thực sự đang liệt kê terminal hay chỉ
    // claude?"* — và trước câu hỏi ấy, nhãn này được suy bằng LOẠI TRỪ: không
    // phải editor thì gọi là terminal. Một `claude` do script/cron/tiến trình
    // khác chạy (không gắn cửa sổ nào) vẫn đọc là "terminal", tức màn hình khai
    // một thứ nó chưa từng kiểm. Đo lúc sửa: cả 5 dòng đang có tty thật và khác
    // nhau (ttys000/003/005/006/010), nên nhãn *đang* đúng — nhưng đúng vì may,
    // không vì có ai kiểm.
    //
    // `ps` in `??` (hoặc `-`) khi tiến trình không có tty điều khiển.
    if tty.is_empty() || tty == "??" || tty == "-" {
        "detached"
    } else {
        "terminal"
    }
}

/// Hits that must suppress a preview, or empty if it is safe to carry.
pub fn preview_risk(text: &str) -> Vec<String> {
    crate::redaction::leak_scan(text, &[])
        .into_iter()
        .filter(|l| SECRET_LABELS.contains(&l.as_str()))
        .collect()
}

