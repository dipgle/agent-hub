//! The Claude CLI sessions running on this machine — read-only.
//!
//! This is hub's OTHER job, and the one the owner actually asked for: he runs
//! `claude` in terminals on this Mac and wants to watch and drive that work
//! from a phone. Everything here observes; nothing here starts, stops, or types
//! into a session. Driving comes later and will be its own module, because a
//! read-only view can ship (and be trusted) on its own.
//!
//! Three facts about this machine decided the shape, all measured 2026-08-08:
//!
//!   1. `claude agents --json` lists live sessions WITHOUT needing a TTY, but
//!      only for one account: acc1 had 9, acc2 had 2, acc3 had 3. An account is
//!      selected by `CLAUDE_CONFIG_DIR`, and the default account is selected by
//!      that variable being ABSENT — pointing it at `~/.claude` reports "not
//!      logged in". So: one call per account, and the default account's entry
//!      must clear the variable rather than set it.
//!   2. Transcripts live at `<transcript_root>/projects/<slug>/<id>.jsonl` and
//!      are appended live. On this machine acc2/acc3 symlink `projects` back to
//!      acc1, so one root covers all three.
//!   3. `cwd` is NOT the project: all 14 live sessions were started from
//!      `~/Documents/projects`, the parent folder. The session NAME is what
//!      carries meaning ("Tiếp tục dwork"), and `projects-87` is autogenerated.

