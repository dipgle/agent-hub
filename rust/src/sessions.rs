pub fn pending_question(tail: &str) -> Option<Asking> {
    let mut asked: Vec<(String, Asking)> = Vec::new();
    let mut answered: HashSet<String> = HashSet::new();
    for line in tail.lines() {
        let Ok(record) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        let Some(blocks) = record
            .get("message")
            .and_then(|m| m.get("content"))
            .and_then(|c| c.as_array())
        else {
            continue;
        };
        for b in blocks {
            match b.get("type").and_then(|t| t.as_str()) {
                Some("tool_use") if b.get("name").and_then(Value::as_str) == Some(ASK_TOOL) => {
                    let Some(id) = b.get("id").and_then(Value::as_str) else {
                        continue;
                    };
                    // NGUYÊN BẢNG, không phải câu đầu. Bảng nhiều câu chỉ gửi đi
                    // được khi trả lời hết, nên cắt lấy câu 0 là dựng sẵn một
                    // phiên kẹt — xem `Asking::rest`.
                    let Some(qs) = b.pointer("/input/questions").and_then(Value::as_array) else {
                        continue;
                    };
                    let mut all = qs.iter().map(question_of);
                    let Some(first) = all.next() else {
                        continue;
                    };
                    asked.push((
                        id.to_string(),
                        Asking {
                            header: first.header,
                            question: first.question,
                            options: first.options,
                            multi: first.multi,
                            rest: all.collect(),
                        },
                    ));
                }
                Some("tool_result") => {
                    if let Some(id) = b.get("tool_use_id").and_then(Value::as_str) {
                        answered.insert(id.to_string());
                    }
                }
                _ => {}
            }
        }
    }
    // Cái CUỐI còn treo: hỏi xong rồi hỏi tiếp thì câu sau mới là câu đang chờ.
    let (_, mut asking) = asked.into_iter().rev().find(|(id, _)| !answered.contains(id))?;
    // Điều 5: chữ này rời khỏi máy (vào ảnh chụp, vào Telegram) nên phải qua
    // cổng quét rò rỉ như mọi phần xem trước khác. Có dấu hiệu thì giữ lại chữ,
    // KHÔNG giữ lại sự thật là phiên đang kẹt.
    let risky = |t: &str| !preview_risk(t).is_empty();
    if risky(&asking.question) || asking.options.iter().any(|o| risky(o)) {
        asking.question = "(màn có dấu hiệu bí mật — mở phiên trên máy để đọc)".to_string();
        asking.options = Vec::new();
    }
    // Cổng quét chạy trên TỪNG câu, không chỉ câu đầu: một bảng có thể hỏi
    // chuyện vô hại ở tab 1 và dán nguyên một khoá ở tab 2, và chính tab 2 mới
    // là thứ nút bấm sắp mang ra khỏi máy. Câu nào dính thì giữ chữ câu ấy —
    // giấu cả bảng thì mất luôn sự thật là bảng có mấy câu.
    for q in &mut asking.rest {
        if risky(&q.question) || q.options.iter().any(|o| risky(o)) {
            q.question = "(màn có dấu hiệu bí mật — mở phiên trên máy để đọc)".to_string();
            q.options = Vec::new();
        }
    }
    Some(asking)
}

/// Một mục `questions[i]` trong lời gọi `AskUserQuestion` → [`Question`].
fn question_of(q: &Value) -> Question {
    Question {
        header: q.get("header").and_then(Value::as_str).unwrap_or_default().to_string(),
        question: q.get("question").and_then(Value::as_str).unwrap_or_default().to_string(),
        options: q
            .get("options")
            .and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .filter_map(|o| o.get("label").and_then(Value::as_str))
                    .map(str::to_string)
                    .collect()
            })
            .unwrap_or_default(),
        multi: q.get("multiSelect").and_then(Value::as_bool).unwrap_or(false),
    }
}

/// Tên công cụ `claude` dùng khi nó dừng lại hỏi chủ máy.
const ASK_TOOL: &str = "AskUserQuestion";

fn pending_subagents(tail: &str, background: &HashSet<String>) -> usize {
    let mut started: Vec<String> = Vec::new();
    let mut finished: HashSet<String> = HashSet::new();
    for line in tail.lines() {
        let Ok(record) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        let Some(blocks) = record
            .get("message")
            .and_then(|m| m.get("content"))
            .and_then(|c| c.as_array())
        else {
            continue;
        };
        for b in blocks {
            match b.get("type").and_then(|t| t.as_str()) {
                Some("tool_use") => {
                    let name = b.get("name").and_then(|n| n.as_str()).unwrap_or("");
                    if name == "Agent" || name == "Task" {
                        if let Some(id) = b.get("id").and_then(|i| i.as_str()) {
                            started.push(id.to_string());
                        }
                    }
                }
                Some("tool_result") => {
                    if let Some(id) = b.get("tool_use_id").and_then(|i| i.as_str()) {
                        finished.insert(id.to_string());
                    }
                }
                _ => {}
            }
        }
    }
    let stopped = stopped_background_calls(tail);
    started
        .iter()
        .filter(|id| {
            if background.contains(*id) {
                !stopped.contains(*id)
            } else {
                !finished.contains(*id)
            }
        })
        .count()
}

/// Walk the tail backwards to the newest real conversation turn.
pub fn parse_tail(tail: &str, background: &HashSet<String>) -> TranscriptTail {
    let (context_tokens, model) = last_usage(tail);
    let mut out = TranscriptTail {
        pending_subagents: pending_subagents(tail, background),
        context_tokens,
        model,
        ..Default::default()
    };
    for line in tail.lines().rev() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let Ok(record) = serde_json::from_str::<Value>(line) else {
            // A partial first line is expected: the tail starts mid-file.
            continue;
        };
        let kind = record.get("type").and_then(|t| t.as_str()).unwrap_or("");
        if kind == "permission-mode" && out.permission_mode.is_none() {
            out.permission_mode = record
                .get("permissionMode")
                .and_then(|m| m.as_str())
                .map(str::to_string);
        }
        if !is_conversation(kind) {
            continue;
        }
        // Newest wins: keep scanning backwards only for what is still missing,
        // never overwrite a turn already found with an older one.
        if out.last_text.is_some() {
            continue;
        }
        out.last_role = record
            .get("message")
            .and_then(|m| m.get("role"))
            .and_then(|r| r.as_str())
            .map(str::to_string)
            .or_else(|| Some(kind.to_string()));
        out.last_text = text_of(&record).map(|t| truncate(&t, PREVIEW_CHARS));
        out.last_ts = record
            .get("timestamp")
            .and_then(|t| t.as_str())
            .map(str::to_string);
        // Stop once BOTH are known: the newest turn and the mode it runs under.
        if out.last_text.is_some() && out.permission_mode.is_some() {
            break;
        }
    }
    out
}

fn read_tail(path: &Path) -> Result<String> {
    let mut file = std::fs::File::open(path)?;
    let len = file.metadata()?.len();
    if len > TAIL_BYTES {
        file.seek(SeekFrom::Start(len - TAIL_BYTES))?;
    }
    let mut buf = Vec::with_capacity(TAIL_BYTES as usize);
    file.read_to_end(&mut buf)?;
    Ok(String::from_utf8_lossy(&buf).to_string())
}

/// Đọc ĐẦU tệp nhật ký — nơi phiên nói nó sinh ra để làm gì.
///
/// Dùng khi phần đuôi không đủ bằng chứng về dự án (đo 2026-08-12: 2 trong 4
/// phiên như vậy — chúng đang bàn chuyện không nêu đường dẫn tệp nào). Mấy lượt
/// ĐẦU thì gần như luôn có: chủ máy mở phiên bằng một câu gọi tên dự án, rồi
/// những việc đầu tiên là đọc `CLAUDE.md`, `PLAN.md` của chính dự án ấy.
///
/// 64 KB, một lần đọc nhỏ, và chỉ chạy cho phiên chưa đoán được.
fn read_head(path: &Path) -> Result<String> {
    let mut file = std::fs::File::open(path)?;
    let mut buf = vec![0u8; 64 * 1024];
    let n = file.read(&mut buf)?;
    buf.truncate(n);
    Ok(String::from_utf8_lossy(&buf).to_string())
}

fn mtime_rfc3339(path: &Path) -> Option<String> {
    let modified = std::fs::metadata(path).ok()?.modified().ok()?;
    let ts: chrono::DateTime<chrono::Utc> = modified.into();
    Some(ts.to_rfc3339_opts(chrono::SecondsFormat::Secs, true))
}

/// Ask one account's CLI what it has running.
fn list_account(account: &ClaudeAccountCfg, cli: &str) -> Result<Vec<Value>> {
    // Absent variable = default account. Setting it to ~/.claude reports "not
    // logged in", so the default account MUST clear it, not point at it.
    let env = vec![(
        "CLAUDE_CONFIG_DIR".to_string(),
        account
            .config_dir
            .as_deref()
            .filter(|d| !d.is_empty())
            .map(|d| {
                crate::config::expand_home(Path::new(d))
                    .to_string_lossy()
                    .to_string()
            }),
    )];
    let out = run(
        cli,
        &["agents", "--json"],
        RunOpts {
            timeout: Some(LIST_TIMEOUT),
            env,
            ..Default::default()
        },
    )?;
    if out.timed_out {
        anyhow::bail!("`{cli} agents --json` timed out after {}ms", out.ms);
    }
    if out.code != Some(0) {
        anyhow::bail!(
            "`{cli} agents --json` exit {:?}: {}",
            out.code,
            truncate(
                if out.stderr.trim().is_empty() {
                    &out.stdout
                } else {
                    &out.stderr
                },
                200
            )
        );
    }
    let value: Value = serde_json::from_str(&out.stdout).map_err(|e| {
        anyhow::anyhow!("unparseable JSON: {e}; head={}", truncate(&out.stdout, 200))
    })?;
    Ok(value.as_array().cloned().unwrap_or_default())
}

/// Every process on the machine as `pid -> ppid`, in one `ps` call.
///
/// One call, not one per session: walking a parent chain with a `ps` per hop
/// costs a process spawn per hop and — worse — reads a tree that is moving
/// while it is read, so a chain could point at a pid that has already been
/// recycled.
fn parent_map() -> std::collections::HashMap<i64, i64> {
    let mut map = std::collections::HashMap::new();
    let out = run(
        "ps",
        &["-eo", "pid=,ppid="],
        RunOpts {
            timeout: Some(Duration::from_secs(10)),
            ..Default::default()
        },
    );
    match out {
        Ok(r) if r.code == Some(0) => {
            for line in r.stdout.lines() {
                let mut it = line.split_whitespace();
                if let (Some(pid), Some(ppid)) = (it.next(), it.next()) {
                    if let (Ok(pid), Ok(ppid)) = (pid.parse::<i64>(), ppid.parse::<i64>()) {
                        map.insert(pid, ppid);
                    }
                }
            }
        }
        Ok(r) => logging::warn("ps_tree_failed", json!({ "code": r.code })),
        Err(e) => logging::warn("ps_tree_failed", json!({ "err": e.to_string() })),
    }
    map
}

/// Làm mới RIÊNG "phiên đang làm gì", không dựng lại cả ảnh chụp.
///
/// Hà 2026-08-11: *"trạng thái phiên đang làm gì đồng bộ lên ui hơi chậm, bạn
