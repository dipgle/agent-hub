/// What a fork opened from the phone is allowed to touch: reading, nothing else.
///
/// Three measurements on 2026-08-08 pinned this exact list, and each one ruled
/// out an option that looked reasonable on paper:
/// - `--tools ""` (no tools at all) FAILS on a session whose history contains
///   tool calls: the model keeps trying to call one and the run comes back
///   `is_error` — *"The model's tool call could not be parsed"*. Every real
///   session here is tool-heavy, so "just take the tools away" is not on offer.
/// - `--disallowedTools` WITHOUT an allowlist still loads the full tool schema.
///   One sentence cost **$0.2185** that way and blew a $0.20 per-call cap.
/// - With this allowlist, a fork asked to enumerate its own tools answers
///   exactly `Glob · Grep · Read`, and the same question costs **$0.0356**.
///
/// So the fence is structural rather than behavioural: a fork opened from a
/// phone has no hand to write with, and no prompt can talk it into growing one.
/// It is also the cost lever — a smaller tool schema is a smaller prompt.
const FORK_TOOLS: &str = "Read,Grep,Glob";

/// One `claude` turn on a FORK of a live session.
///
/// Fork, not resume-in-place, is the whole safety story: the original
/// transcript comes back byte-identical (measured twice — 15222 bytes on the
/// first handover, and 7380 bytes / 10 lines / unchanged mtime on the probe
/// that fixed `FORK_TOOLS`), so nothing done from the phone can damage the
/// thread it is looking at. The answer lands in a NEW session id, which is why
/// callers must present it as an aside instead of filing it under the parent.
struct ForkReply {
    new_session_id: String,
    text: String,
    cost_usd: f64,
}

/// Dollars per megabyte of transcript, measured: a 0.986 MB session cost $1.72
/// to load on 2026-08-08. `--resume` re-reads the whole conversation, so the
/// price tracks the session's LENGTH, not the length of the question.
const USD_PER_MB: f64 = 1.75;

/// What one fork of `session` is expected to cost, from the size of its log.
///
/// Used for the per-call ceiling instead of borrowing triage's flat $0.50. That
/// figure was sized for a chat message and is smaller than the load cost of 13
/// of the 14 sessions live on this machine — and a call killed by its own
/// ceiling is still BILLED, so a flat cap would have meant paying for nothing,
/// repeatedly, on exactly the big sessions worth asking about.
pub fn fork_cost_estimate(cfg: &Config, session: &LiveSession) -> f64 {
    let root = cfg.claude_transcript_root();
    let by_cwd = transcript_path(&root, &session.cwd, &session.session_id);
    let path = if by_cwd.exists() {
        Some(by_cwd)
    } else {
        find_transcript(&root, &session.session_id)
    };
    // No transcript found means no estimate — return 0 so the caller falls back
    // to its floor rather than inventing a ceiling out of a missing file.
    let bytes = path
        .and_then(|p| std::fs::metadata(p).ok())
        .map(|m| m.len())
        .unwrap_or(0);
    (bytes as f64 / 1_000_000.0) * USD_PER_MB
}

/// `claude` thoát khác 0 — dựng lỗi cho NGƯỜI ĐỌC, ở đúng một chỗ.
///
/// Hai chỗ gọi `claude` (hỏi trên bản fork · nói tiếp vào phiên) từng có cùng
/// một đoạn: cắt 200 ký tự đầu của stderr-hoặc-stdout rồi ném ra. Khi `claude`
/// hỏng, thứ nó in là một envelope JSON và **200 ký tự đầu đúng là phần vô
/// dụng** — `is_error/duration_api_ms/num_turns/session_id/total_cost_usd/
/// usage…` — còn `result` (LÝ DO) nằm sau. Đo 2026-08-11: một lần hỏi bên lề
/// hỏng, tiêu 0.53 đơn vị hạn mức, và câu duy nhất còn lại nói được đúng "có
/// hỏng". Hai chỗ gọi thì chỗ thứ ba sẽ chép lại y thế — nên luật đứng ở nguồn.
///
/// Log giữ CẢ CÂU (tệp nằm trên chính máy này); ack đi ra phòng chat thì lấy
/// đúng `result` và vẫn phải qua cổng quét rò rỉ như mọi thứ rời khỏi máy.
fn claude_failed(session_id: &str, out: &crate::exec::RunOut) -> anyhow::Error {
    let payload = if out.stderr.trim().is_empty() {
        &out.stdout
    } else {
        &out.stderr
    };
    logging::error(
        "claude_call_failed",
        json!({
            "session": session_id,
            "code": out.code,
            "stdout": truncate(&out.stdout, 4000),
            "stderr": truncate(&out.stderr, 4000),
        }),
    );
    let reason = serde_json::from_str::<Value>(payload.trim())
        .ok()
        .and_then(|v| {
            v.get("result")
                .or_else(|| v.get("error"))
                .and_then(|r| r.as_str())
                .map(|s| s.to_string())
        })
        .unwrap_or_else(|| payload.to_string());
    let safe = if preview_risk(&reason).is_empty() {
        truncate(&reason, 200)
    } else {
        "[hub ẩn lý do: có thể chứa bí mật — xem log trên máy]".to_string()
    };
    anyhow::anyhow!("claude exit {:?}: {}", out.code, safe)
}

fn fork_call(cfg: &Config, session: &LiveSession, prompt: &str) -> Result<ForkReply> {
    // Cap the CALL. `--resume` loads the whole conversation, so one handover on
    // a 986 KB session cost $1.72 on its first real run (2026-08-08) and a day
    // ceiling only refuses the NEXT call.
    //
    // The cap is derived from this session rather than fixed: doubled headroom
    // over the estimate stops a runaway without refusing honest work, and a
    // floor keeps tiny sessions from getting a ceiling of nearly zero.
    let estimate = fork_cost_estimate(cfg, session);
    let cap = (estimate * 2.0).max(cfg.call.max_budget_usd);
    logging::info(
        "fork_call_budget",
        json!({
            "session": session.session_id,
            "estimate_usd": estimate,
            "cap_usd": cap,
        }),
    );
    let per_call = cap.to_string();
    // Pin the working directory to the session's own, so `Read`/`Grep` resolve
    // against the work being asked about rather than wherever `hubd` was
    // started from.
    let cwd = crate::config::expand_home(Path::new(&session.cwd));
    let out = run(
        &cfg.claude_cli,
        &[
            "-p",
            "--resume",
            &session.session_id,
            "--fork-session",
            "--tools",
            FORK_TOOLS,
            "--disable-slash-commands",
            "--strict-mcp-config",
            "--max-budget-usd",
            &per_call,
            "--output-format",
            "json",
        ],
        RunOpts {
            cwd: cwd.is_dir().then_some(cwd.as_path()),
            input: Some(prompt.to_string()),
            timeout: Some(Duration::from_secs(cfg.call.timeout_sec)),
            env: vec![(
                "CLAUDE_CONFIG_DIR".into(),
                account_dir(cfg, &session.account),
            )],
        },
    )?;
    if out.timed_out {
        anyhow::bail!("quá {}s", cfg.call.timeout_sec);
    }
    if out.code != Some(0) {
        return Err(claude_failed(&session.session_id, &out));
    }
    let v: Value = serde_json::from_str(&out.stdout)
        .map_err(|e| anyhow::anyhow!("kết quả không đọc được: {e}"))?;
    let cost_usd = v
        .get("total_cost_usd")
        .and_then(|c| c.as_f64())
        .unwrap_or(0.0);
    // A budget stop or an unparseable tool call comes back with exit 0 and
    // `is_error: true` — and it is BILLED. Reporting that as an answer would
    // put "The model's tool call could not be parsed" on screen as if the
    // session had said it, so fail loudly and let the caller book the cost.
    if v.get("is_error").and_then(Value::as_bool) == Some(true) {
        anyhow::bail!(
            "claude báo lỗi (đã tính ${cost_usd:.4}): {}",
            truncate(
                v.get("result").and_then(|s| s.as_str()).unwrap_or("(rỗng)"),
                200
            )
        );
    }
    let new_id = v
        .get("session_id")
        .and_then(|s| s.as_str())
        .unwrap_or_default()
        .to_string();
    if new_id.is_empty() || new_id == session.session_id {
        // Without a NEW id there is nothing to continue into, and writing back
        // into the live session is exactly what fork exists to avoid.
        anyhow::bail!("không nhận được session id mới (nhận: {new_id:?})");
    }
    Ok(ForkReply {
        new_session_id: new_id,
        text: v
            .get("result")
            .and_then(|s| s.as_str())
            .unwrap_or_default()
            .trim()
            .to_string(),
        cost_usd,
    })
}

/// Ask a session to write its own handover, on a FORK.
pub fn handover(cfg: &Config, session: &LiveSession) -> Result<Handover> {
    let reply = fork_call(cfg, session, HANDOVER_PROMPT)?;
    Ok(Handover {
        source_id: session.session_id.clone(),
        source_name: session.name.clone(),
        new_session_id: reply.new_session_id.clone(),
        // The handover text is a session talking about its own work, so it can
        // quote anything the session saw — same gate as every other preview.
        checkpoint: gate_preview(
            &reply.text,
            "[hub ẩn bàn giao: có thể chứa bí mật — mở phiên trên máy để xem]",
        ),
        cost_usd: reply.cost_usd,
        ts: crate::logging::now_iso(),
        resume_command: format!(
            "cd {} && claude --resume {}",
            session.cwd, reply.new_session_id
        ),
    })
}

/// A question asked ALONGSIDE a running session, and its answer.
///
/// "Alongside" is the product claim and the reason this is not just a chat
/// message: the answer knows everything the session knows up to now, while the
/// session itself gains no turn and loses no time.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct Aside {
    pub source_id: String,
    pub source_name: String,
    /// Where the answer actually lives — a fork, never the parent.
    pub new_session_id: String,
    pub question: String,
    pub answer: String,
    /// See `Handover::cost_usd` — recorded, never published.
    #[serde(default, skip_serializing)]
    pub cost_usd: f64,
    pub ts: String,
}

/// Ask a live session a question without touching it (UC-S05b, level 2).
///
/// The question comes from the owner (`parse_command` refuses anyone else), so
/// it is an order, not untrusted content — but the ANSWER can quote anything
/// the session ever read, which is why it goes through the same preview gate as
/// every other screen.
/// Hỏi chen ngang bằng ĐÚNG cách chủ máy làm khi ngồi trước terminal: `/btw`.
///
/// Hà 2026-08-11: *"rõ ràng tôi đang ở session để làm việc, vậy 1 câu hỏi chen
/// ngang nó phải tương đương như tôi đang làm trên cli terminal chứ?"*. Đúng —
/// và `claude` có sẵn cách ấy, chính CLI gợi ý trên màn: *"Use /btw to ask a
/// quick side question without interrupting Claude's current work"*.
///
/// Vì sao nó hơn hẳn đường fork cho phiên có cửa sổ:
/// - **Giá.** Fork phải nạp lại toàn bộ nhật ký — đo thật 0.99 MB → **1.72**
///   đơn vị hạn mức cho MỘT câu hỏi, và đó là lý do `fe-aside` phải có cổng
///   chặn và mặc định không gọi. `/btw` hỏi phiên đang sống, nó trả lời bằng
///   ngữ cảnh đã nằm sẵn trong đầu — gần như không tốn gì.
/// - **Độ sát.** Fork dựng lại ngữ cảnh TỪ NHẬT KÝ; phiên sống thì biết cả việc
///   đang dở giữa chừng, thứ chưa kịp vào nhật ký.
///
/// 📌 **Cái giá — ĐO LẠI 2026-08-11, và nó KHÁC điều tệp này từng khẳng định.**
/// Câu cũ ở đây (và trên trang, và trong `UC.md`) là *"phiên gốc CÓ thêm một
/// lượt"*. Chạy thật trên phiên `3e9a7fd6` (Terminal.app, ttys001): `/btw` mở
/// một **bảng bên** ngay trong TUI — câu trả lời hiện ra kèm chân bảng
/// *"↑/↓ to scroll · c to copy · f to fork · Esc to close"* — và **KHÔNG một
/// byte nào vào nhật ký**: phiên ấy vẫn chưa có tệp `.jsonl` sau khi trả lời
/// xong. Nên lời hứa đúng là: *nhật ký phiên gốc không đổi, nhưng câu hỏi ăn
/// vào NGỮ CẢNH đang chạy của phiên*.
///
/// ⚠ Điều CHƯA đo: phiên đã có nhật ký sẵn thì `/btw` có ghi thêm không. Phép
/// đo trên chạy đúng một ca — phiên trắng. Đừng suy rộng lần nữa.
///
/// Phiên không gõ vào được (nền, trong editor, không cửa sổ) thì vẫn fork như cũ.
fn ask_via_btw(session: &LiveSession, question: &str) -> Option<String> {
    // MỖI đường lui đều phải nói ra vì sao. Bản đầu trả `None` cho cả ba lý do
    // — không có cửa sổ · không hỏi được Terminal · màn không đọc được — và
    // đường lui ấy là một lời gọi `claude --fork-session` TỐN THẬT.
    //
    // Đo 2026-08-11: phiên `projects-71` (tty ttys008) hiện `host: "terminal"`
    // trên màn nên trang hứa sẽ gõ thẳng, nhưng nó chạy trong **terminal tích
    // hợp của VS Code**, không phải Terminal.app ⟹ `window_of` trả `None` ⟹ rơi
    // về fork ⟹ fork hỏng và tiêu 0.53 đơn vị hạn mức. Trong log KHÔNG có một
    // dòng nào nói vì sao `/btw` không chạy: đúng cái luật "không lỗi im lặng"
    // mà tệp này viết ra, hỏng ngay trong tệp này.
    let window = match crate::keys::window_of(&session.tty) {
        Ok(Some(w)) => w,
        Ok(None) => {
            logging::info(
                "btw_no_window",
                json!({
                    "session": session.session_id,
                    "tty": session.tty,
                    "why": "không cửa sổ Terminal.app nào mang tty này (phiên trong VS Code / iTerm / tmux?)",
                    "fallback": "fork",
                }),
            );
            return None;
        }
        Err(e) => {
            logging::warn(
                "btw_window_probe_failed",
                json!({ "session": session.session_id, "tty": session.tty, "err": e.to_string(), "fallback": "fork" }),
            );
            return None;
        }
    };
    // DỌN BẢNG CŨ trước đã.
    //
    // Đo 2026-08-11: một bảng `/btw` còn mở từ lượt trước NUỐT luôn câu hỏi của
    // lượt này — gõ vào thì bảng đóng lại chứ không mở bảng mới, hub chờ hết 60
    // giây rồi rơi về fork (và fork chết vì phiên ấy chưa có nhật ký). Một lượt
    // hỏng vì rác của lượt trước là thứ chắc chắn tái diễn vào ngày có người hỏi
    // hai câu liền nhau, nên dọn ngay ở đây — đừng trông vào việc lượt trước đã
    // tự dọn.
    if let crate::keys::Look::Saw { body, .. } = crate::keys::look(&session.tty, 40) {
        if body.contains(BTW_PANEL_DONE) {
            logging::info(
                "btw_stale_panel_closed",
                json!({ "session": session.session_id, "why": "bảng /btw của lượt trước còn mở" }),
            );
            let _ = crate::keys::press(window, "esc");
            std::thread::sleep(Duration::from_millis(700));
        }
    }
    // Ảnh màn TRƯỚC khi hỏi, để biết cái gì là mới.
    let before = match crate::keys::look(&session.tty, 40) {
        crate::keys::Look::Saw { body, .. } => body,
        // Màn không đọc được thì cũng không đọc được câu trả lời ⟹ đừng gõ vào
        // phiên của người ta rồi bỏ đấy.
        other => {
            logging::info(
                "btw_screen_unreadable",
                json!({
                    "session": session.session_id,
                    "why": match &other {
                        crate::keys::Look::Blind { why } => why.clone(),
                        crate::keys::Look::Withheld { risk, .. } =>
                            format!("màn có dấu hiệu bí mật: {}", risk.join(",")),
                        crate::keys::Look::Saw { .. } => unreachable!("nhánh Saw đã bắt ở trên"),
                    },
                    "fallback": "fork",
                }),
            );
            return None;
        }
    };
    if let Err(e) = crate::keys::type_into(window, &format!("/btw {question}"), true) {
        logging::warn("btw_type_failed", json!({ "session": session.session_id, "err": e.to_string() }));
        return None;
    }
    // Chờ BẢNG TRẢ LỜI ĐÓNG LẠI, không phải chờ "màn đổi và phiên thôi bận".
    //
    // Đo 2026-08-11, và đây là chỗ bản đầu trả về một câu trả lời GIẢ: `/btw`
    // vẽ một bảng bên trong TUI, và trong lúc nó đang viết, màn ĐÃ đổi
    // (`body != before`) còn `is_busy` thì KHÔNG bắt được — đồng hồ
    // `(2m 5s · ↓ …)` là của một lượt chạy bình thường, bảng `/btw` không có nó.
    // Kết quả: hub tóm cả màn hình lúc còn `· Answering…` rồi gửi về điện thoại
    // như thể đó là câu trả lời — kèm nguyên cái logo `Claude Code v2.1.227`.
    //
    // Thứ `claude` bảo đảm là CHÂN BẢNG: `Esc to close` chỉ hiện khi bảng đã
    // viết xong. Neo vào nó, y như `is_busy` neo vào cái đồng hồ chứ không vào
    // động từ đang quay.
    for _ in 0..30 {
        std::thread::sleep(Duration::from_secs(2));
        let crate::keys::Look::Saw { body, .. } = crate::keys::look(&session.tty, 60) else {
            continue;
        };
        if body == before || !btw_panel_finished(&body) {
            continue;
        }
        let answer = btw_answer(&body, question);
        // Đóng bảng lại. Bỏ bước này là để lại một bảng chắn ngang phiên của
        // người khác — hub mở ra thì hub phải dọn, y như `/stop` phải đóng được
        // cái cửa sổ mà `/new` mở ra.
        if let Err(e) = crate::keys::press(window, "esc") {
            logging::warn(
                "btw_panel_close_failed",
                json!({ "session": session.session_id, "err": e.to_string() }),
            );
        }
        return Some(answer);
    }
    // Hết trần chờ: nói ra ĐÃ NHÌN THẤY GÌ, không chỉ "chưa thấy". Dòng cuối của
    // màn là thứ phân biệt "nó vẫn đang viết" với "câu hỏi rơi vào hư không" —
    // và chính chỗ này từng để lọt cả một lượt hỏng mà log không kể được gì.
    // Màn đã qua cổng quét rò rỉ (`look` trả `Saw`), nên một dòng là an toàn.
    let seen = match crate::keys::look(&session.tty, 4) {
        crate::keys::Look::Saw { body, .. } => body
            .lines()
            .rev()
            .find(|l| !l.trim().is_empty())
            .map(|l| truncate(l.trim(), 120))
            .unwrap_or_default(),
        _ => "(không đọc lại được màn)".to_string(),
    };
    logging::info(
        "btw_no_answer_yet",
        json!({ "session": session.session_id, "last_line": seen, "fallback": "fork" }),
    );
    None
}

/// Chân bảng `/btw`. Có nó nghĩa là BẢNG ĐANG MỞ — **không** nghĩa là đã viết xong.
const BTW_PANEL_DONE: &str = "Esc to close";

/// Chữ `claude` in trong lúc bảng còn đang viết câu trả lời.
const BTW_ANSWERING: &str = "Answering";

/// Dòng lệnh chính hub vừa gõ, `claude` vẽ lại ở đầu bảng.
const BTW_ECHO: &str = "/btw";

/// Bảng đã viết XONG chưa.
///
/// Đo 2026-08-11, lần vá thứ hai của cùng một lỗi: bản trước neo vào
/// `Esc to close` và tưởng đó là dấu "xong". Ảnh chụp thật lúc đang viết:
///
/// ```text
///     /btw Tóm tắt trong 1 câu: phiên này đang làm việc gì?
///       ✳ Answering…
///     Esc to close
/// ```
///
/// Chân bảng có mặt NGAY TỪ ĐẦU — nó nói "bảng đang mở", không nói "đã xong".
/// Nên phải đòi thêm vế phủ định: **không còn** `Answering`. Cùng một bài học
/// với `is_busy` (neo vào đồng hồ, không vào động từ) và với `look` (ba kết cục
/// khác nhau đừng gộp làm một).
pub fn btw_panel_finished(screen: &str) -> bool {
    screen.contains(BTW_PANEL_DONE) && !screen.contains(BTW_ANSWERING)
}

/// Bóc CÂU TRẢ LỜI ra khỏi màn hình.
///
/// Màn mang cả logo khởi động, cả dòng `/btw <câu hỏi>` vừa gõ, cả chân bảng
/// hướng dẫn phím. Gửi nguyên màn về điện thoại thì người đọc phải tự lọc — mà
/// hub đọc được thì hub lọc được. Cắt theo hai mốc `claude` tự vẽ: dòng chứa
/// câu hỏi vừa gõ, và chân bảng.
pub fn btw_answer(screen: &str, question: &str) -> String {
    let lines: Vec<&str> = screen.lines().collect();
    let key = question.trim();
    // Mốc đầu: dòng `claude` vẽ lại chính lệnh vừa gõ. Neo vào `/btw` chứ không
    // vào câu hỏi — TUI ngắt dòng theo bề ngang cửa sổ, nên một câu hỏi dài
    // KHÔNG nằm trọn trên một dòng và phép so "dòng nào chứa câu hỏi" trượt
    // sạch (đo 2026-08-11: câu trả lời trả về còn nguyên dòng `/btw …` ở đầu).
    //
    // Vế `char_indices` không phải cho đẹp: cắt chuỗi tiếng Việt theo BYTE giữa
    // một ký tự nhiều byte là panic ngay tại chỗ, và chỗ này chạy trong daemon.
    let prefix: String = key.chars().take(16).collect();
    let start = lines
        .iter()
        .rposition(|l| l.contains(BTW_ECHO))
        .or_else(|| {
            lines
                .iter()
                .position(|l| l.contains(key) || (!prefix.is_empty() && l.contains(&prefix)))
        })
        .map(|i| i + 1)
        .unwrap_or(0);
    let end = lines
        .iter()
        .rposition(|l| l.contains(BTW_PANEL_DONE))
        .unwrap_or(lines.len());
    let body: Vec<&str> = lines[start.min(end)..end]
        .iter()
        .map(|l| l.trim_end())
        .collect();
    let text = body.join("\n").trim().to_string();
    // Không cắt được thì thà trả cả màn còn hơn trả rỗng — nhưng nói ra là đã
    // không cắt được, đừng im lặng đưa một đống chữ.
    if text.is_empty() {
        logging::info("btw_answer_uncut", json!({ "why": "không tìm thấy mốc cắt trên màn" }));
        return screen.trim().to_string();
    }
    text
}

pub fn ask_aside(cfg: &Config, session: &LiveSession, question: &str) -> Result<Aside> {
    let question = question.trim();
    if question.is_empty() {
        anyhow::bail!("chưa có câu hỏi");
    }

    // Đường THẲNG trước: hỏi chính phiên đang sống, y như ngồi trước máy.
    if let Some(screen) = ask_via_btw(session, question) {
        return Ok(Aside {
            source_id: session.session_id.clone(),
            source_name: session.name.clone(),
            // Không có fork nào cả — câu trả lời nằm trong CHÍNH phiên ấy.
            new_session_id: session.session_id.clone(),
            question: question.to_string(),
            answer: gate_preview(
                &screen,
                "[hub ẩn câu trả lời: màn có thể chứa bí mật — mở phiên trên máy để xem]",
            ),
            cost_usd: 0.0,
            ts: crate::logging::now_iso(),
        });
    }
    // Fork cần một CUỘC HỘI THOẠI để `--resume`. Phiên vừa mở, chưa nói lượt
    // nào, thì không có gì để nạp — và `claude` trả đúng câu ấy: *"No
    // conversation found with session ID: …"*, exit 1, sau khi đã tính tiền
    // khởi động. Đo 2026-08-11. Nói thẳng trước khi gọi thì rẻ hơn, và câu trả
    // lời nói được việc cần làm thay vì một mã lỗi.
    let path = transcript_path(
        &cfg.claude_transcript_root(),
        &session.cwd,
        &session.session_id,
    );
    if !path.exists() {
        logging::info(
            "aside_no_transcript",
            json!({ "session": session.session_id, "path": path.display().to_string() }),
        );
        anyhow::bail!(
            "phiên này chưa nói lượt nào nên không có bản sao để hỏi. Mở cửa sổ của nó rồi \
             hỏi thẳng, hoặc giao cho nó một việc trước đã."
        );
    }

    // Say out loud that this is a side question. Without it the fork reads the
    // transcript as "we were in the middle of X" and carries on working —
    // which it cannot do here anyway (read-only tools), so it would just
    // narrate a plan nobody asked for.
    let prompt = format!(
        "Đây là câu hỏi CHEN NGANG từ chủ máy, hỏi qua điện thoại. Bạn đang ở một \
         bản sao (fork) của phiên — phiên gốc vẫn chạy và KHÔNG bị ảnh hưởng.\n\
         Chỉ TRẢ LỜI câu hỏi dựa trên ngữ cảnh phiên; không tiếp tục công việc dở, \
         không đề xuất kế hoạch, không sửa file (bạn chỉ có công cụ đọc).\n\
         Trả lời bằng tiếng Việt, ngắn gọn, đi thẳng vào câu hỏi.\n\n\
         Câu hỏi: {question}"
    );
    let reply = fork_call(cfg, session, &prompt)?;
    Ok(Aside {
        source_id: session.session_id.clone(),
        source_name: session.name.clone(),
        new_session_id: reply.new_session_id,
        question: question.to_string(),
        answer: gate_preview(
            &reply.text,
            "[hub ẩn câu trả lời: có thể chứa bí mật — mở phiên trên máy để xem]",
        ),
        cost_usd: reply.cost_usd,
        ts: crate::logging::now_iso(),
    })
}

/// Show the text, or say why it is hidden — never show it half-redacted and
/// never blank it without a reason.
fn gate_preview(text: &str, hidden: &str) -> String {
    if preview_risk(text).is_empty() {
        text.to_string()
    } else {
        hidden.to_string()
    }
}

/// A session hub started, and how to find it again.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct Started {
    pub session_id: String,
    pub project: String,
    pub cwd: String,
    pub task: String,
    pub ts: String,
    /// Mở bằng CỬA SỔ terminal thật hay bằng phiên nền.
    ///
    /// Có trường này vì câu trả lời gửi ra điện thoại phải nói đúng thứ vừa
    /// xảy ra, mà `/new` có hai đường (cửa sổ, và `--bg` khi đường kia hỏng).
    /// Suy ngược từ `kind` ở chỗ gọi thì được một lời đoán; ghi lại ở đây thì
    /// được một sự thật.
    #[serde(default)]
    pub window: bool,
}

/// The session id out of `claude --bg`'s human-readable output.
///
/// The id is the FIRST token after the marker, not the rest of the line. A
/// session started without a prompt prints
/// `backgrounded · 6514f454 (idle — send a prompt to start)`, and taking the
/// whole tail stored that entire sentence as the session id — after which
/// `/session`, `/ask`, `/tell` and `/stop` all silently failed to match it,
/// while hub reported the session as started. Pure so the shape can be pinned
/// by a test instead of by another live run.
pub fn parse_backgrounded_id(stdout: &str) -> Option<&str> {
    stdout
        .lines()
        .find_map(|l| l.trim().strip_prefix("backgrounded · "))
        .and_then(|s| s.split_whitespace().next())
        .filter(|s| !s.is_empty())
}

/// Start a new background session in a project folder (UC-S06).
///
/// `--bg` returns in about a second with an id and leaves the agent running —
/// measured 2026-08-08: the row shows up in `claude agents` as
/// `kind: "background"`, named after the task, at `permission_mode: "dontAsk"`.
///
/// Two things follow from that last fact and neither is decoration:
/// - It runs UNATTENDED with tools, so it runs behind `DENIED_TOOLS` (above):
///   no push/merge/reset, no ssh/scp/sudo/rm, no curl. The human approval step
///   non-negotiable #1 asks for is the owner typing the task and pressing the
///   button.
/// - hub cannot tell what it costs. The transcript records no price and
///   `claude agents` reports none, so there is nothing to add up. What hub can
///   do is show that it is running and offer a stop — control and visibility
///   instead of a number that would be invented.
///
/// # Tài khoản
///
/// Mở phiên **trên tài khoản được chọn**.
///
/// `account = None` là tài khoản mặc định (biến `CLAUDE_CONFIG_DIR` bị XOÁ —
/// trỏ nó vào `~/.claude` sẽ báo "not logged in", xem chú thích đầu tệp).
/// Trước 2026-08-09 hàm này luôn xoá biến, tức máy có ba tài khoản mà từ điện
/// thoại chỉ mở được phiên trên acc1 — Hà hỏi đúng chỗ đó.
/// Mở phiên trong một CỬA SỔ TERMINAL THẬT, rồi ghép nó với hàng `claude agents`.
///
/// Ghép bằng **tty**, không bằng tên: tên phiên do `claude` tự đặt (`projects-31`)
/// nên hub không đoán trước được, còn `sessionId` thì chưa tồn tại lúc vừa gõ
/// lệnh. `tty` thì Terminal trả về ngay khi dựng cửa sổ, và `claude agents` khai
/// đúng nó — hai đầu gặp nhau ở đó.
///
/// ⚠ Thứ tự tham số là bẫy đã trả giá một lần (`CLAUDE.md` §10):
/// `--disallowedTools` là VARIADIC, nên đề bài phải đứng TRƯỚC nó; đặt sau thì
/// đề bài bị nuốt thành một mẫu công cụ nữa và phiên dựng lên mà không có việc.
fn start_in_terminal(
    cfg: &Config,
    root: &Path,
    project: &str,
    dir: &Path,
    task: &str,
    account: Option<&str>,
) -> Result<Started> {
    let cmd = terminal_command(
        &cfg.claude_cli,
        root,
        task,
        account.and_then(|a| account_dir(cfg, a)).as_deref(),
    );
    let (window, tty) = crate::keys::open_window(&cmd)?;
    let tty_short = tty.rsplit('/').next().unwrap_or(&tty).to_string();
    logging::info(
        "new_window_opened",
        json!({ "window": window, "tty": tty_short, "task": truncate(task, 80) }),
    );

    // ĐƯỜNG RẺ TRƯỚC: id phiên chính là TÊN TỆP nhật ký.
    //
    // 🔴 Hà 2026-08-12, sau khi gõ `/new mailler` ba lần: đo ra `command_done
    // New` **64,7 giây**, trong đó `new_window_opened` xảy ra ở giây thứ 7 —
    // tức **57 giây chỉ để chờ `claude agents` khai id**. Mà mỗi vòng chờ gọi
    // `claude agents` cho cả ba tài khoản, và trên máy đang swap một lượt như
    // thế mất 15–60 giây. Cái giá thật không phải là sự chậm: **anh tưởng hỏng
    // nên gõ lại, và máy mở ra HAI phiên mailler**.
    //
    // `claude` tạo `~/.claude/projects/<slug>/<session_id>.jsonl` ngay khi phiên
    // bắt đầu, nên id nằm sẵn trên đĩa — một lượt `read_dir`, vài mili giây.
    // Chỉ nhận tệp sinh SAU lúc mở cửa sổ, và lấy cái mới nhất.
    let opened_at = std::time::SystemTime::now();
    let fast_deadline = std::time::Instant::now() + Duration::from_secs(20);
    while std::time::Instant::now() < fast_deadline {
        std::thread::sleep(Duration::from_millis(500));
        if let Some(id) = newest_transcript_since(&cfg.claude_transcript_root(), root, opened_at) {
            logging::info(
                "new_session_matched_by_transcript",
                json!({ "session": id, "tty": tty_short }),
            );
            return Ok(Started {
                session_id: id,
                project: project.to_string(),
                cwd: dir.to_string_lossy().to_string(),
                task: task.to_string(),
                ts: crate::logging::now_iso(),
                window: true,
            });
        }
    }

    // Hết 20 giây mà chưa có nhật ký ⟹ phiên chưa chào đời, và nguyên nhân đã
    // đo được là hộp tin-thư-mục (mỗi cặp tài khoản × thư mục hỏi đúng một
    // lần). Bấm hộ rồi chờ thêm một lượt — cùng cách với lượt tự đóng sổ.
    if answer_trust_dialog(&tty_short).is_some() {
        let after = std::time::Instant::now() + Duration::from_secs(20);
        while std::time::Instant::now() < after {
            std::thread::sleep(Duration::from_millis(500));
            if let Some(id) = newest_transcript_since(&cfg.claude_transcript_root(), root, opened_at)
            {
                logging::info(
                    "new_session_matched_by_transcript",
                    json!({ "session": id, "tty": tty_short, "after": "trust_dialog" }),
                );
                return Ok(Started {
                    session_id: id,
                    project: project.to_string(),
                    cwd: dir.to_string_lossy().to_string(),
                    task: task.to_string(),
                    ts: crate::logging::now_iso(),
                    window: true,
                });
            }
        }
    }

    // Đường cũ, giữ làm lưới đỡ: nhật ký chưa kịp sinh (phiên kẹt ở hộp thoại
    // duyệt MCP chẳng hạn) thì vẫn còn `claude agents` để hỏi.
    //
    // Đếm bằng ĐỒNG HỒ, không đếm bằng số vòng: mỗi vòng gọi `claude agents`
    // cho từng tài khoản, nên "30 vòng × 2 giây" trên thực tế là 90 giây chứ
    // không phải 60 — và câu báo lỗi nói "60 giây" sẽ là một con số bịa.
    let deadline = std::time::Instant::now() + Duration::from_secs(40);
    while std::time::Instant::now() < deadline {
        std::thread::sleep(Duration::from_secs(2));
        if let Some(row) = snapshot(cfg)
            .sessions
            .into_iter()
            .find(|s| !s.tty.is_empty() && s.tty == tty_short)
        {
            return Ok(Started {
                session_id: row.session_id,
                project: project.to_string(),
                cwd: dir.to_string_lossy().to_string(),
                task: task.to_string(),
                ts: crate::logging::now_iso(),
                window: true,
            });
        }
    }
    anyhow::bail!("mở được cửa sổ ({tty_short}) nhưng `claude agents` chưa khai phiên nào trên đó sau 60 giây")
}

/// Hộp *"tin thư mục này chứ?"* — và **chỉ** hộp ấy.
///
/// Thuần, để cái ranh giới hẹp này kiểm được mà không cần một cửa sổ Terminal.
///
/// Vì sao hẹp đến thế: bấm một con số vào hộp chọn là **trả lời thay chủ máy**,
/// việc hub không được phép làm. Hộp này là ngoại lệ có căn cứ, và căn cứ nằm ở
/// chỗ nó KHÔNG hỏi về công việc — nó hỏi *"thư mục này có phải của anh không"*
/// về đúng thư mục **hub vừa tự mở cửa sổ vào**, dưới **tài khoản của chính chủ
/// máy**, ở đúng chỗ phiên trước đang làm việc. Câu trả lời đã được chủ máy nói
/// ra từ trước bằng hành động, chỉ là `claude` ghi "đã tin" theo từng cặp
/// (`CLAUDE_CONFIG_DIR`, đường tuyệt đối) nên nó hỏi lại mỗi khi gặp cặp mới.
///
/// Nhận theo CHỮ của lựa chọn, và đòi cả ba: có `trust`, có `folder`, và KHÔNG
/// mở đầu bằng `no` (hộp có sẵn một lựa chọn *"No, exit"*). Câu chữ đổi ⟹ không
/// khớp ⟹ hub rơi về nhánh báo-và-giữ-nguyên, tức **hỏng thì hỏng về phía im
/// lặng**, không phải về phía bấm bừa.
pub fn trust_dialog_choice(choices: &[(usize, String)]) -> Option<usize> {
    choices.iter().find_map(|(n, label)| {
        let l = label.trim().to_lowercase();
        (l.contains("trust") && l.contains("folder") && !l.starts_with("no")).then_some(*n)
    })
}

/// Nhìn cửa sổ hub vừa mở; kẹt ở hộp tin-thư-mục thì bấm hộ. Trả về số đã bấm.
///
/// 🔴 Hà 2026-08-13, sau khi xem tận mắt một cửa sổ đứng im 22 phút: *"bấm hộ
/// đi, phải kiểm tra được và bấm luôn 1"*.
///
/// Chỉ gọi cho cửa sổ **hub vừa tự mở** và chỉ khi phiên **chưa chào đời** —
/// hai điều kiện ấy không nằm trong hàm này mà nằm ở chỗ gọi, vì chúng là lý do
/// việc bấm hộ chấp nhận được.
pub fn answer_trust_dialog(tty: &str) -> Option<usize> {
    // 🔴 Ba lý do "không bấm" phải PHÂN BIỆT ĐƯỢC. Hà 2026-08-13: *"vẫn đang
    // đứng im"* — cửa sổ kẹt nguyên trên hộp, hàm này trả `None`, và log không
    // có một dòng nào. `screen_of` gộp `Withheld` (màn có vẻ chứa bí mật) và
    // `Blind` (không đọc được) vào cùng một `None` với "đọc được nhưng không
    // phải hộp ấy" — ba chuyện khác hẳn nhau, và chỉ một trong ba là bình
    // thường. Cùng cái bẫy `keys::look` sinh ra để gỡ, lặp lại ở chỗ gọi.
    let looked = crate::keys::look(tty, 24);
    let choices = match looked {
        crate::keys::Look::Saw { choices, .. } => choices,
        // Màn bị giữ lại thì chỉ còn một CON SỐ lựa chọn, không có chữ — mà
        // luật nhận hộp này đọc CHỮ ("trust" + "folder"). Không đọc được chữ
        // thì KHÔNG bấm: bấm một con số vào một hộp chưa nhận diện được là trả
        // lời thay chủ máy về một câu hub không biết nội dung.
        crate::keys::Look::Withheld { choices, risk } => {
            logging::info(
                "trust_dialog_screen_withheld",
                json!({ "tty": tty, "choices": choices, "risk": risk,
                        "why": "màn có dấu hiệu bí mật nên chữ bị giữ — không nhận diện được hộp, KHÔNG bấm" }),
            );
            return None;
        }
        crate::keys::Look::Blind { why } => {
            logging::warn(
                "trust_dialog_screen_blind",
                json!({ "tty": tty, "why": why }),
            );
            return None;
        }
    };
    let Some(n) = trust_dialog_choice(&choices) else {
        if !choices.is_empty() {
            logging::info(
                "trust_dialog_not_this_box",
                json!({ "tty": tty, "choices": choices.len(),
                        "why": "có hộp chọn nhưng không phải hộp tin-thư-mục — hub không trả lời thay chủ máy" }),
            );
        }
        return None;
    };
    let w = match crate::keys::window_of(tty) {
        Ok(Some(w)) => w,
        // Không im lặng: mất cửa sổ ở đây nghĩa là phiên mới vẫn kẹt, và chỗ gọi
        // phải biết để còn giữ cửa sổ cũ lại.
        other => {
            logging::warn(
                "trust_dialog_window_gone",
                json!({ "tty": tty, "detail": format!("{other:?}") }),
            );
            return None;
        }
    };
    match crate::keys::press(w, &n.to_string()) {
        Ok(()) => {
            logging::info(
                "trust_dialog_answered",
                json!({ "tty": tty, "pressed": n,
                        "why": "hộp tin-thư-mục trên cửa sổ CHÍNH HUB vừa mở — Hà uỷ quyền 2026-08-13" }),
            );
            Some(n)
        }
        Err(e) => {
            logging::warn(
                "trust_dialog_press_failed",
                json!({ "tty": tty, "choice": n, "err": e.to_string() }),
            );
            None
        }
    }
}

/// Nhật ký phiên MỚI NHẤT sinh ra sau mốc `since`, trong thư mục khoá của `cwd`.
///
/// Tên tệp chính là `session_id` — đó là cả mẹo: hub biết id mà không phải hỏi
/// `claude agents` (ba lần spawn một binary 279 MB). Chỉ nhận tệp sinh SAU lúc
/// mở cửa sổ, nên phiên cũ trong cùng thư mục không lọt vào.
fn newest_transcript_since(
    root: &Path,
    cwd: &Path,
    since: std::time::SystemTime,
) -> Option<String> {
    let dir = root
        .join("projects")
        .join(transcript_slug(&cwd.to_string_lossy()));
    let mut best: Option<(std::time::SystemTime, String)> = None;
    for e in std::fs::read_dir(&dir).ok()?.flatten() {
        let p = e.path();
        if p.extension().and_then(|x| x.to_str()) != Some("jsonl") {
            continue;
        }
        let Ok(m) = e.metadata().and_then(|m| m.modified()) else {
            continue;
        };
        if m < since {
            continue;
        }
        let Some(id) = p.file_stem().and_then(|s| s.to_str()) else {
            continue;
        };
        if best.as_ref().is_none_or(|(t, _)| m > *t) {
            best = Some((m, id.to_string()));
        }
    }
    best.map(|(_, id)| id)
}

/// Dòng lệnh gõ vào cửa sổ Terminal mới.
///
/// Tách riêng để KIỂM ĐƯỢC cái bẫy đã trả giá một lần: `--disallowedTools` là
/// variadic, nên đề bài phải đứng trước nó (`CLAUDE.md` §10). Một hàm thuần thì
/// test đọc thẳng được thứ tự ấy; nếu để nội tuyến trong hàm mở cửa sổ thì chỉ
/// một phiên thật mới phát hiện được sai, và lúc đó nó đã dựng một phiên rỗng.
/// Mở một phiên MỚI mang theo bản bàn giao, rồi đóng cửa sổ cũ.
///
/// 🔴 Bản đầu (đêm 2026-08-12) mở bằng `--resume <id bản fork>` — và đo trên
/// máy thì nó **vô nghĩa**: phiên mới `758baa85` sinh lúc 00:09:49 đã **62%
/// ngữ cảnh** ngay lúc 00:12:44, vì `--resume` nối tiếp bản fork nên nó vác
/// nguyên lịch sử cũ sang. Đóng sổ mà ngữ cảnh không giảm thì không đóng được
/// cái gì; tệ hơn, phiên mới lập tức đủ điều kiện đóng sổ lần nữa ⟹ **vòng
/// lặp**: cứ rảnh là hub lại thay một cửa sổ. Hà bắt đúng lúc: *"sao lại reset
/// 1 loạt tất cả các phiên thế, đã vượt 60% context đâu"*.
///
/// Đúng ý ngay từ đầu (*"tự chủ động đóng phiên rồi mở phiên MỚI luôn"*): phiên
/// mới phải **trắng ngữ cảnh**, chỉ mang theo bản bàn giao làm đề bài. Đó cũng
/// là toàn bộ lý do `HANDOVER_PROMPT` tồn tại.
///
/// Kết quả một lượt thay cửa sổ — đủ dữ kiện để NÓI THẬT về nó.
///
/// `old_kept` là trường quan trọng nhất và là trường sinh sau đẻ muộn nhất: xem
/// khối 🔴 trong [`start_fresh_after_handover`].
pub struct FreshWindow {
    /// tty của cửa sổ vừa mở.
    pub tty: String,
    /// id phiên mới, nếu nó đã kịp sinh nhật ký để ghép.
    pub new_id: Option<String>,
    /// vì sao chưa đóng được cửa sổ cũ (khi ĐÃ thử đóng).
    pub closed_err: Option<String>,
    /// cửa sổ cũ được GIỮ LẠI có chủ ý — vì phiên mới chưa chào đời.
    pub old_kept: bool,
    /// hộp chọn đang chờ trên cửa sổ mới, nếu đọc được.
    pub asking: Vec<(usize, String)>,
}

/// Mở một phiên MỚI mang theo bản bàn giao, rồi đóng cửa sổ cũ.
pub fn start_fresh_after_handover(
    cfg: &Config,
    session: &LiveSession,
    checkpoint: &str,
) -> Result<FreshWindow> {
    let task = format!(
        "Tiếp quản phiên trước (phiên cũ đã đầy ngữ cảnh nên hub đóng sổ và mở phiên này). \
         BÀN GIAO:\n\n{checkpoint}\n\nĐọc xong thì làm tiếp việc kế tiếp trong bàn giao."
    );
    let cwd = Path::new(&session.cwd);
    let cmd = terminal_command(
        &cfg.claude_cli,
        cwd,
        &task,
        account_dir(cfg, &session.account).as_deref(),
    );
    let opened_at = std::time::SystemTime::now();
    let (_window, tty) = crate::keys::open_window(&cmd)?;
    let tty_short = tty.rsplit('/').next().unwrap_or(&tty).to_string();
    // Ghép id qua TÊN TỆP nhật ký — cùng mẹo với `/new`, vài mili giây, không
    // phải ba lần spawn `claude agents`.
    // 🔴 BẤM HỘ TRƯỚC, đừng chờ tới khi kết luận "chưa chào đời".
    //
    // Hà 2026-08-13 21:5x: *"phiên dwork tự chuyển do ngữ cảnh đầy lại đang bị
    // kẹt"* · *"lại kẹt khi chuyển phiên kìa"*. Đọc màn `ttys004` ra đúng thủ
    // phạm — cửa sổ kế nhiệm ngồi nguyên trên hộp:
    //
    //     ❯ 1. Yes, I trust this folder
    //       2. No, exit
    //
    // Mã ĐÃ có bước bấm hộ, và nó vẫn không chạy: cửa của nó là
    // `new_id.is_none()`, mà `new_id` vừa được điền — bằng nhật ký của CHÍNH
    // PHIÊN CŨ. Log làm chứng: `handover_window_opened session:0a109818…`, đúng
    // id phiên đang được đóng sổ. `newest_transcript_since` chỉ hỏi "tệp nào
    // mới đổi sau lúc mở cửa sổ", mà phiên cũ vẫn đang ghi tiếp vào nhật ký của
    // nó. Tức một phép đo trả lời ĐÚNG câu nó được hỏi và SAI câu người ta cần.
    //
    // Hai vá, và cả hai đều thu hẹp chỗ đoán:
    // * bấm hộ VÔ ĐIỀU KIỆN trước khi chờ — `trust_dialog_choice` chỉ khớp
    //   đúng hộp ấy, không có hộp thì nó không bấm gì cả, nên gọi sớm không mất
    //   gì mà cứu được đúng ca này;
    // * và loại id phiên CŨ ra khỏi phép ghép, vì "nhật ký vừa đổi" bao gồm cả
    //   nó — xem `newest_transcript_since`.
    if let Some(n) = answer_trust_dialog(&tty_short) {
        logging::info(
            "handover_trust_dialog_answered",
            json!({ "tty": tty_short, "choice": n,
                    "why": "cửa sổ kế nhiệm kẹt ở hộp tin-thư-mục — bấm trước khi chờ" }),
        );
    }
    let mut new_id = None;
    for _ in 0..24 {
        std::thread::sleep(Duration::from_millis(500));
        if let Some(id) = newest_transcript_since(&cfg.claude_transcript_root(), cwd, opened_at) {
            if id != session.session_id {
                new_id = Some(id);
                break;
            }
        }
    }
    // Vẫn chưa có nhật ký ⟹ thử bấm hộ lần nữa: hộp có thể hiện MUỘN hơn lượt
    // gọi ở trên (máy đang swap thì `claude` mất vài giây mới vẽ xong).
    if new_id.is_none() && answer_trust_dialog(&tty_short).is_some() {
        for _ in 0..24 {
            std::thread::sleep(Duration::from_millis(500));
            if let Some(id) = newest_transcript_since(&cfg.claude_transcript_root(), cwd, opened_at)
            {
                if id != session.session_id {
                    new_id = Some(id);
                    break;
                }
            }
        }
    }
    logging::info(
        "handover_window_opened",
        json!({ "tty": tty_short, "session": new_id.clone().unwrap_or_default(), "fresh": true }),
    );

    // 🔴 KHÔNG ĐÓNG CỬA SỔ CŨ KHI PHIÊN MỚI CHƯA CHỨNG MINH NÓ CHÀO ĐỜI.
    //
    // Trả giá thật 2026-08-13 04:30, lượt tự đóng sổ thứ hai: `hanguyen-41`
    // (acc3, 64%) → cửa sổ mới mở ở `ttys000` lúc 04:31:37 với
    // `handover_window_opened session:""` — id RỖNG — rồi 04:31:59 hub đóng cửa
    // sổ cũ như thường lệ. Cửa sổ mới ấy **đứng im 22 phút**, và Hà là người
    // phát hiện: *"mở phiên mới bị dừng giữa chừng"*, kèm ảnh chụp hộp *"Quick
    // safety check: … 1. Yes, I trust this folder"*.
    //
    // Gốc KHÔNG nằm ở hub: gốc dời `~/Documents/projects` → `~/projects` hôm
    // 08-12, mà `claude` ghi "đã tin thư mục này" theo **từng CLAUDE_CONFIG_DIR**
    // — đo trong `.claude.json` của ba tài khoản: acc1 có bản ghi cho
    // `/Users/hanguyen/projects`, **acc2 và acc3 KHÔNG có** (chỉ còn đường cũ).
    // Nên cửa sổ đầu tiên mở dưới acc2/acc3 ở gốc mới luôn dừng ở hộp hỏi ⟹
    // không có nhật ký ⟹ không có id để ghép.
    //
    // Cái sai của hub là **cái nó làm tiếp theo**: id rỗng nghĩa là "chưa thấy
    // phiên nào cả", mà hub vẫn đóng cửa sổ đang làm việc của chủ máy — tức nó
    // phá cái chắc chắn để đổi lấy cái chưa chứng minh, đúng lúc mù nhất. Nay
    // id rỗng ⟹ **giữ nguyên cửa sổ cũ** và đọc màn cửa sổ mới xem nó vướng gì.
    // Hai cửa sổ thì chủ máy đóng bớt được; một phiên đang làm dở bị đóng thì
    // không lấy lại được.
    if new_id.is_none() {
        let asking = crate::keys::screen_of(&tty_short, 24)
            .map(|(_, choices)| choices)
            .unwrap_or_default();
        logging::warn(
            "handover_new_session_never_appeared",
            json!({ "tty": tty_short, "old_session": session.session_id,
                    "asking": asking.len(), "old_window": "giữ nguyên" }),
        );
        return Ok(FreshWindow {
            tty: tty_short,
            new_id: None,
            closed_err: None,
            old_kept: true,
            asking,
        });
    }

    // Đóng cửa sổ CŨ. Hỏng thì KHÔNG coi là hỏng cả việc: phiên mới đã chạy, và
    // một cửa sổ thừa còn mở thì chủ máy đóng bằng tay được — nói ra là đủ.
    let closed_err = match crate::keys::window_of(&session.tty) {
        Ok(Some(w)) => match crate::keys::quit_and_close(w) {
            Ok(()) => None,
            Err(e) => Some(truncate(&e.to_string(), 200)),
        },
        Ok(None) => Some("không tìm thấy cửa sổ của phiên cũ".to_string()),
        Err(e) => Some(truncate(&e.to_string(), 200)),
    };
    if let Some(why) = &closed_err {
        logging::warn(
            "handover_old_window_not_closed",
            json!({ "session": session.session_id, "why": why }),
        );
    }
    Ok(FreshWindow {
        tty: tty_short,
        new_id,
        closed_err,
        old_kept: false,
        asking: Vec::new(),
    })
}

pub fn terminal_command(cli: &str, root: &Path, task: &str, config_dir: Option<&str>) -> String {
    let env_prefix = match config_dir {
        Some(dir) => format!("CLAUDE_CONFIG_DIR={} ", shell_quote(dir)),
        None => String::new(),
    };
    // MỌI mẫu công cụ phải được bọc. Chúng chứa `(`, `)`, `*`, `:` —
    // `Bash(git push:*)` để trần là LỖI CÚ PHÁP của shell, và cửa sổ sẽ mở ra
    // với một dòng đỏ thay vì một phiên. Nhánh `--bg` không dính vì nó truyền
    // argv thẳng, không đi qua shell; nhánh cửa sổ thì có, nên rào chỉ còn là
    // rào khi nó sống sót qua shell.
    let denied = DENIED_TOOLS
        .iter()
        .map(|t| shell_quote(t))
        .collect::<Vec<_>>()
        .join(" ");
    // Đề bài rỗng ⟹ KHÔNG có tham số vị trí nào: cửa sổ mở ra một phiên
    // `claude` trống, đúng như chủ máy tự gõ. Đưa `''` vào đó thì `claude` nhận
    // một đề bài rỗng — khác hẳn với không có đề bài.
    let prompt = if task.is_empty() {
        String::new()
    } else {
        format!("{} ", shell_quote(task))
    };
    // `--permission-mode auto` — đúng chế độ chủ máy vẫn ngồi làm việc.
    //
    // 🔴 Hà 2026-08-12: *"khi dùng lệnh new mở được phiên rồi nhưng chưa chuyển
    // tự động sang auto mode on"*. Phiên hub mở ra ở chế độ mặc định, tức mỗi
    // lần chạm công cụ là một hộp thoại xin phép — mà **người mở đang ở trên
    // điện thoại**: hộp thoại ấy hiện trên một cái màn hình không ai nhìn, và
    // phiên đứng im cho tới lúc có người ngồi vào máy. Đúng phép thử CẦU NỐI:
    // thứ chủ máy làm được ở terminal (bấm shift+tab) mà điện thoại không làm
    // được là một khoảng trống.
    //
    // Giá trị lấy từ `claude --help` trên chính máy này, không lấy từ trí nhớ:
    // `acceptEdits · auto · bypassPermissions · manual · dontAsk · plan`.
    //
    // ⚠ KHÔNG nới điều 1: `--disallowedTools` vẫn nguyên vẹn và vẫn đứng cuối.
    // `auto` bỏ bước HỎI, `DENIED_TOOLS` bỏ bước LÀM — hai thứ khác nhau, và
    // cái rào thật nằm ở vế sau (không push/merge/reset, không ssh/sudo/rm…).
    format!(
        "cd {} && {}{} --permission-mode auto {}--disallowedTools {}",
        shell_quote(&root.to_string_lossy()),
        env_prefix,
        shell_quote(cli),
        prompt,
        denied
    )
}

/// Bọc một chuỗi cho shell — chỉ dùng cho lệnh hub tự dựng, không cho chữ ngoài.
fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

pub fn start_background(
    cfg: &Config,
    project: &str,
    dir: &Path,
    task: &str,
    account: Option<&str>,
) -> Result<Started> {
    let task = task.trim();
    // Đề bài RỖNG được phép — nhưng chỉ trên đường mở cửa sổ thật.
    //
    // Hà 2026-08-12: *"/new -a acc2 -s dwork"* — không có đề bài, và đó là
    // đúng thứ ông ấy làm khi ngồi trước máy: mở một cửa sổ, gõ `claude`, rồi
    // NÓI. Ép phải có đề bài ngay câu đầu là bắt điện thoại làm một việc mà cái
    // bàn phím thật không phải làm. Đường `--bg` thì khác hẳn: nó không có cửa
    // sổ nào để gõ vào, nên một phiên nền không đề bài là một phiên nằm chết
    // (`idle — send a prompt to start`) — chỗ ấy vẫn phải từ chối, xem dưới.
    if !dir.is_dir() {
        anyhow::bail!("không thấy thư mục dự án: {}", dir.display());
    }
    // ORDER IS LOad-BEARING and cost a real run to learn. The prompt is
    // POSITIONAL here — `--bg` and `-p` conflict outright ("--print never
    // starts the interactive session that `claude agents` attaches to") — and
    // `--disallowedTools` is VARIADIC, so a prompt placed after it is eaten as
    // one more tool pattern. The first real `/new` did exactly that: the agent
    // came up with no task at all, reporting itself as
    // "idle — send a prompt to start", and hub cheerfully called it started.
    // Prompt first, variadic last.
    // Mở ở GỐC WORKSPACE, không phải trong thư mục dự án.
    //
    // Hà 2026-08-10: *"ngay từ đầu tôi bảo mọi phiên đều bắt đầu từ thư mục
    // projects rồi mà"* — và đo lại thì đúng: MỌI phiên đang chạy trên máy đều
    // có `cwd = ~/projects`, còn cả ba tài khoản đều đã duyệt đúng
    // thư mục ấy (`hasTrustDialogAccepted: true`).
    //
    // Mở trong thư mục con là mở vào một chỗ CHƯA tài khoản nào duyệt, nên
    // phiên dựng lên rồi kẹt ngay ở hộp thoại MCP và chết — đúng lỗi Hà gặp khi
    // chọn acc2. Việc thuộc dự án nào thì nói trong ĐỀ BÀI, chứ không cần đổi
    // thư mục làm việc: `claude` đọc `CLAUDE.md` của cả cây từ gốc.
    let root = cfg.workspace_root.clone();
    let task_with_project = if task.is_empty() {
        String::new()
    } else {
        format!("[{project}] {task}")
    };

    // ĐƯỜNG CHÍNH: mở một cửa sổ Terminal thật, y như chủ máy tự mở.
    //
    // Hà 2026-08-11: *"cli claude cài trên máy tôi, hub là cầu kết nối ra ui"*.
    // Một phiên `--bg` là hạng phiên ông ấy KHÔNG bao giờ tự tạo khi ngồi trước
    // máy: không cửa sổ ⟹ không màn sống, không `/btw`, không dòng "đang làm
    // gì", và muốn nói chen vào phải DỪNG nó trước. Ba tính năng dựng ngày
    // 2026-08-10 đều không chạy được trên hạng phiên ấy — đó là bằng chứng rõ
    // nhất rằng nó lệch khỏi thứ có thật ở đầu bên kia cây cầu.
    //
    // `--bg` vẫn giữ làm ĐƯỜNG LUI (không mở nổi cửa sổ, hoặc chủ máy tắt cờ),
    // vì nó sống độc lập với Terminal — đóng cửa sổ là mất phiên cửa sổ, còn
    // `--bg` thì không.
    if cfg.new_in_terminal {
        match start_in_terminal(cfg, &root, project, dir, &task_with_project, account) {
            Ok(started) => return Ok(started),
            Err(e) => logging::warn(
                "new_in_terminal_failed",
                json!({ "err": e.to_string(), "falling_back_to": "--bg" }),
            ),
        }
    }

    // Đường lui `--bg` KHÔNG có cửa sổ nào để gõ vào, nên đề bài rỗng ở đây là
    // một phiên nằm chết mà hub lại báo "đã mở".
    if task_with_project.is_empty() {
        anyhow::bail!(
            "không mở được cửa sổ terminal, mà phiên nền thì phải có đề bài ngay từ đầu \
             (không có cửa sổ nào để gõ vào) — gõ lại kèm việc cần làm"
        );
    }
    let mut args: Vec<&str> = vec!["--bg", &task_with_project, "--disallowedTools"];
    args.extend_from_slice(&DENIED_TOOLS);

    let out = run(
        &cfg.claude_cli,
        &args,
        RunOpts {
            cwd: Some(root.as_path()),
            input: None,
            timeout: Some(Duration::from_secs(120)),
            env: vec![(
                "CLAUDE_CONFIG_DIR".into(),
                account.and_then(|a| account_dir(cfg, a)),
            )],
        },
    )?;
    if out.code != Some(0) {
        // Chưa có id nào để gọi tên: phiên đang được TẠO ra thì hỏng.
        return Err(claude_failed("(phiên mới, chưa có id)", &out));
    }
    // Human-readable output, not JSON — the id is on the "backgrounded · <id>"
    // line. Parse defensively: a silent miss here would report success while
    // hub has no idea which session it just started (and cannot stop it).
    let short = parse_backgrounded_id(&out.stdout)
        .map(str::to_string)
        .ok_or_else(|| {
            anyhow::anyhow!(
                "không đọc được id phiên nền từ: {}",
                truncate(out.stdout.trim(), 200)
            )
        })?;

    // The short id is a prefix; resolve it to the full one so every other verb
    // (`/session`, `/ask`, `/tell`, `/stop`) has something to match on. The
    // agent takes a moment to register, so retry rather than storing a prefix
    // that nothing will ever match.
    let mut full = None;
    for _ in 0..8 {
        full = snapshot(cfg)
            .sessions
            .into_iter()
            .find(|s| s.session_id.starts_with(&short))
            .map(|s| s.session_id);
        if full.is_some() {
            break;
        }
        std::thread::sleep(Duration::from_secs(1));
    }
    let full = full.unwrap_or_else(|| {
        // Say it rather than quietly handing back a prefix: the session IS
        // running, the owner should know hub lost track of its full id.
        logging::warn(
            "background_session_id_unresolved",
            json!({ "short": short, "effect": "focus cursor holds a prefix; /session may not match" }),
        );
        short.clone()
    });

    // A started session is not a working session. Measured 2026-08-08: a
    // background agent opened in any folder under this workspace comes up
    // `state: "blocked"`, sitting on an interactive dialog —
    //   "2 new MCP servers found in this project. Select any you wish to
    //    enable. … Space to select · Enter to confirm · Esc to reject all"
    // — raised by the workspace's own `.mcp.json` (project-agent, vault). It
    // waits for a keypress that nobody on a phone can give, writes no
    // transcript, and never does the task. `--strict-mcp-config` does not
    // suppress it, nor does `--mcp-config '{"mcpServers":{}}'` (both tried).
    //
    // Reporting "🚀 đã mở phiên" over that would be the exact failure this
    // project keeps writing down: a green message for work that never ran. So
    // look, and if it is stuck, stop it and say what the one-time fix is.
    let mut stuck = false;
    for _ in 0..7 {
        std::thread::sleep(Duration::from_secs(2));
        let Some(row) = snapshot(cfg)
            .sessions
            .into_iter()
            .find(|s| s.session_id == full)
        else {
            continue;
        };
        if row.state.as_deref() == Some("blocked") {
            stuck = true;
            break;
        }
        // Any transcript at all means it got past the dialog and is working.
        if find_transcript(&cfg.claude_transcript_root(), &full).is_some() {
            break;
        }
    }
    if stuck {
        logging::warn(
            "background_session_blocked",
            json!({ "session": full, "cwd": dir.display().to_string(), "cause": "interactive MCP approval dialog" }),
        );
        // Leave nothing hanging: a blocked agent does no work and only clutters
        // the list the owner is trying to read.
        //
        // Và câu trả lời phải nói ĐÚNG chuyện đã xảy ra. Bản trước khẳng định
        // "nên đã dừng lại" một cách vô điều kiện — kể cả khi `run` không spawn
        // nổi (nhánh `if let Ok` nuốt luôn `Err`, không log) hoặc `claude stop`
        // trả mã khác 0. Người đọc tin là máy đã sạch, trong khi một phiên kẹt
        // vẫn nằm đó ăn chỗ trong danh sách.
        let stopped = match run(
            &cfg.claude_cli,
            &["stop", short_id(&full)],
            RunOpts {
                cwd: None,
                input: None,
                timeout: Some(Duration::from_secs(30)),
                // Dừng trên ĐÚNG tài khoản vừa mở phiên: `claude stop` ở tài
                // khoản khác sẽ báo "no job matching".
                env: vec![(
                    "CLAUDE_CONFIG_DIR".into(),
                    account.and_then(|a| account_dir(cfg, a)),
                )],
            },
        ) {
            Ok(out) if out.code == Some(0) => true,
            Ok(out) => {
                logging::warn(
                    "blocked_session_stop_failed",
                    json!({ "session": full, "code": out.code,
                            "stderr": truncate(out.stderr.trim(), 120) }),
                );
                false
            }
            Err(e) => {
                // Không chạy nổi lệnh dừng là chuyện phải nói: nó khác hẳn
                // "chạy rồi mà không dừng được".
                logging::warn(
                    "blocked_session_stop_unrunnable",
                    json!({ "session": full, "err": e.to_string() }),
                );
                false
            }
        };
        let fate = if stopped {
            "nên đã dừng lại".to_string()
        } else {
            format!(
                "và tôi KHÔNG dừng được nó — phiên {} vẫn còn, tự dừng bằng: claude stop {}",
                short_id(&full),
                short_id(&full)
            )
        };
        anyhow::bail!(
            "phiên mở ra nhưng KẸT ngay ở hộp thoại duyệt MCP của dự án (workspace có .mcp.json: project-agent, vault) — nó chờ một phím bấm mà điện thoại không gõ được, {}. Cách gỡ, làm MỘT LẦN cho mỗi dự án trên máy: cd {} && claude  →  Enter (duyệt) hoặc Esc (bỏ hết), rồi thoát. Sau đó /new chạy được.",
            fate,
            dir.display()
        );
    }

    Ok(Started {
        session_id: full,
        project: project.to_string(),
        cwd: dir.to_string_lossy().to_string(),
        task: task.to_string(),
        ts: crate::logging::now_iso(),
        window: false,
    })
}

/// The id `claude stop` accepts — the SHORT one.
///
/// `claude agents` reports both: `id` is 8 characters, `sessionId` is the full
/// uuid. `stop` only matches the short form and answers a full uuid with
/// *"No job matching '…'. Run 'claude agents' to list running sessions."* —
/// which hub logged as a warning while telling the owner the session had
/// stopped. Everything else here keys on the full id, so the narrowing happens
/// at the one call that needs it.
fn short_id(session_id: &str) -> &str {
    session_id.split('-').next().unwrap_or(session_id)
}

/// `/close` — ĐÓNG HẲN: thoát CLI rồi đóng luôn cửa sổ Terminal.
///
/// 🔴 Hà 2026-08-13, ba câu liền: *"chưa có lệnh đóng phiên đóng luôn cửa sổ?"*
/// · *"đang đứng ở phiên nào thì cần lệnh đóng hẳn"* · và câu chốt phân vai:
/// *"ah stop là dừng rồi vậy dùng close"*.
///
/// Anh đúng, và nó chỉ ra một động từ bị gánh hai việc: `/stop` **dừng** một
/// phiên nền (hội thoại còn nguyên, `/tell` nói tiếp được), nhưng gặp phiên có
/// cửa sổ thì nó lại đi thoát-CLI-rồi-đóng-cửa-sổ. Một chữ, hai kết cục khác
/// hẳn nhau về mức mất mát, và người bấm không có cách nào biết mình sắp nhận
/// cái nào. Nay tách: `/stop` chỉ dừng, `/close` mới đóng.
///
/// **Không hỏi ai mở cửa sổ.** Luật cũ chỉ cho đóng phiên do chính hub mở
/// (`started_by_hub`), lý do viết là *"cửa sổ chủ máy tự mở là việc của chủ
/// máy"*. Nghe hợp lý mà đọc ngược phép thử của dự án: gần như mọi cửa sổ trên
/// máy này do chủ máy tự mở, nên luật ấy làm lệnh đóng vô dụng **đúng ở chỗ hay
/// dùng nhất** — ngồi trước máy thì gõ `/exit` rồi đóng cửa sổ là xong, cầm
/// điện thoại thì không. Và "việc của chủ máy" thì chính chủ máy đang bấm.
///
/// Cửa gác đúng chỗ không phải *ai mở*, mà *phiên có đang làm dở không*:
/// `quit_and_close` gõ `/exit`, chờ tới 30 giây cho `claude` chạy hết lượt đang
/// xếp hàng, rồi **từ chối đóng** nếu tab vẫn bận — vì đóng lúc ấy sẽ bật hộp
/// thoại "terminate running processes", thứ khoá mồm mọi lệnh automation sau nó.
/// Trả `None` khi phiên là phiên NỀN (đã dừng xong, không có cửa sổ nào để
/// đóng), `Some(window)` khi đã gõ `/exit` và cửa sổ ấy đang chờ được đóng.
pub fn close_session(cfg: &Config, session: &LiveSession) -> Result<Option<i64>> {
    if session.kind == "background" {
        // Phiên nền không có cửa sổ nào để đóng: đóng hẳn nó CHÍNH LÀ dừng nó.
        // Nói ra ở chỗ gọi, đừng để người bấm tưởng vừa có một cửa sổ biến mất.
        stop_background(cfg, session)?;
        return Ok(None);
    }
    logging::info(
        "session_close_window",
        json!({ "session": session.session_id, "kind": session.kind,
                "by_hub": session.started_by_hub }),
    );
    let window = crate::keys::window_of(&session.tty)
        .map_err(|e| anyhow::anyhow!("không dò được cửa sổ terminal của phiên: {e}"))?
        .ok_or_else(|| {
            anyhow::anyhow!(
                "không còn cửa sổ terminal nào chạy {} — phiên có lẽ đã tắt rồi",
                if session.tty.is_empty() {
                    "(không rõ tty)"
                } else {
                    &session.tty
                }
            )
        })?;
    // Chỉ GÕ lệnh thoát. Việc canh "chạy nốt chưa" là của vòng chạy — Hà
    // 2026-08-13: *"30 giây kiểm tra 1 lần nếu chưa xong thì chờ tiếp"*.
    //
    // Cửa sổ RẢNH thoát bằng `exit` của shell, không phải `/exit` của TUI: gõ
    // `/exit` vào một dấu nhắc zsh ra `zsh: no such file or directory: /exit`
    // rồi cửa sổ nằm nguyên đó — hub báo "đang đóng" cho một việc không bao
    // giờ xảy ra.
    if session.host == "shell" {
        crate::keys::type_into(window, "exit", true)?;
    } else {
        crate::keys::send_exit(window)?;
    }
    Ok(Some(window))
}

/// Stop a background session. Its conversation is kept, so it can be continued.
pub fn stop_background(cfg: &Config, session: &LiveSession) -> Result<()> {
    if session.kind != "background" {
        // `claude stop` chỉ biết job NỀN, nên với phiên có cửa sổ thì "dừng"
        // không có nghĩa gì thi hành được — và tự ý đóng cửa sổ ở đây là đúng
        // cái lẫn vai mà `/close` vừa sinh ra để gỡ. Chỉ đường, đừng đoán.
        anyhow::bail!(
            "phiên này chạy trong một cửa sổ Terminal nên không có gì để 'dừng' — \
             dùng /close để thoát CLI và đóng hẳn cửa sổ, hoặc /key esc để cắt lượt đang chạy"
        );
    }
    let out = run(
        &cfg.claude_cli,
        &["stop", short_id(&session.session_id)],
        RunOpts {
            cwd: None,
            input: None,
            timeout: Some(Duration::from_secs(60)),
            env: vec![(
                "CLAUDE_CONFIG_DIR".into(),
                account_dir(cfg, &session.account),
            )],
        },
    )?;
    if out.code != Some(0) {
        return Err(claude_failed(&session.session_id, &out));
    }
    Ok(())
}

/// What one turn added to a session that was continued in place.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct Told {
    pub session_id: String,
    pub source_name: String,
    pub text: String,
    pub answer: String,
    /// See `Handover::cost_usd` — recorded, never published.
    #[serde(default, skip_serializing)]
    pub cost_usd: f64,
    pub ts: String,
}

/// Continue a session IN PLACE — a real next turn, not an aside (UC-S05).
///
/// The wall here is the CLI's, not a policy hub invented: resuming a live
/// background agent is refused outright —
/// *"Session … is currently running as a background agent (bg). Use `claude
/// agents` to find and attach to it, or add --fork-session to branch off a
/// copy."* So "talk into a session while it works" has no path at all from a
/// phone; `attach` needs a terminal on the machine, and forking is a different
/// thing (UC-S05b level 2, which hub already offers).
///
/// What DOES work, measured 2026-08-08: stop the agent first, then resume. The
/// session id stays the same and the transcript grows (8434 → 11529 bytes,
/// 16 → 22 records) — a genuine next turn on the same thread.
pub fn tell(cfg: &Config, session: &LiveSession, text: &str) -> Result<Told> {
    let text = text.trim();
    if text.is_empty() {
        anyhow::bail!("chưa có nội dung");
    }
    if session.kind != "background" {
        anyhow::bail!(
            "chỉ nói tiếp được vào phiên do hub mở. Phiên này mở từ terminal/VS Code — dùng \"hỏi bên lề\" để hỏi mà không đụng vào nó."
        );
    }
    if session.status.as_deref() == Some("busy") {
        anyhow::bail!(
            "phiên đang chạy dở nên claude không cho nối vào. Dừng nó trước (nút Dừng), hoặc dùng \"hỏi bên lề\" để hỏi mà không cắt việc."
        );
    }

    let estimate = fork_cost_estimate(cfg, session);
    let cap = (estimate * 2.0).max(cfg.call.max_budget_usd).to_string();
    let cwd = crate::config::expand_home(Path::new(&session.cwd));
    // Same denylist the session was started with: continuing a task must not
    // quietly hand it powers its first turn did not have.
    let mut args: Vec<&str> = vec!["-p", "--resume", &session.session_id, "--disallowedTools"];
    args.extend_from_slice(&DENIED_TOOLS);
    args.extend_from_slice(&["--max-budget-usd", &cap, "--output-format", "json"]);
    let out = run(
        &cfg.claude_cli,
        &args,
        RunOpts {
            cwd: cwd.is_dir().then_some(cwd.as_path()),
            input: Some(text.to_string()),
            timeout: Some(Duration::from_secs(cfg.call.timeout_sec)),
            env: vec![(
                "CLAUDE_CONFIG_DIR".into(),
                account_dir(cfg, &session.account),
            )],
        },
    )?;
    if out.timed_out {
        anyhow::bail!("quá {}s", cfg.call.timeout_sec);
    }
    if out.code != Some(0) {
        return Err(claude_failed(&session.session_id, &out));
    }
    let v: Value = serde_json::from_str(&out.stdout)
        .map_err(|e| anyhow::anyhow!("kết quả không đọc được: {e}"))?;
    let cost_usd = v
        .get("total_cost_usd")
        .and_then(|c| c.as_f64())
        .unwrap_or(0.0);
    if v.get("is_error").and_then(Value::as_bool) == Some(true) {
        anyhow::bail!(
            "claude báo lỗi (đã tính ${cost_usd:.4}): {}",
            truncate(
                v.get("result").and_then(|s| s.as_str()).unwrap_or("(rỗng)"),
                200
            )
        );
    }
    let got = v
        .get("session_id")
        .and_then(|s| s.as_str())
        .unwrap_or_default();
    if got != session.session_id {
        // A NEW id means the turn landed somewhere else — the opposite of what
        // this verb promises. Say so instead of reporting a cheerful success on
        // a thread the owner is not looking at.
        anyhow::bail!("lượt này rơi vào phiên khác ({got}) chứ không nối vào phiên cũ");
    }
    Ok(Told {
        session_id: session.session_id.clone(),
        source_name: session.name.clone(),
        text: text.to_string(),
        answer: gate_preview(
            v.get("result")
                .and_then(|s| s.as_str())
                .unwrap_or_default()
                .trim(),
            "[hub ẩn câu trả lời: có thể chứa bí mật — mở phiên trên máy để xem]",
        ),
        cost_usd,
        ts: crate::logging::now_iso(),
    })
}

/// `CLAUDE_CONFIG_DIR` for an account label — `None` means the ambient account.
fn account_dir(cfg: &Config, account: &str) -> Option<String> {
    cfg.claude_accounts_or_ambient()
        .into_iter()
        .find(|a| a.name == account)
        .and_then(|a| a.config_dir)
        .filter(|d| !d.is_empty())
        .map(|d| {
            crate::config::expand_home(Path::new(&d))
                .to_string_lossy()
                .to_string()
        })
}

/// Sessions per account, for a one-line summary.
pub fn count_by_account(snap: &SessionsSnapshot) -> BTreeMap<String, usize> {
    let mut counts = BTreeMap::new();
    for s in &snap.sessions {
        *counts.entry(s.account.clone()).or_insert(0) += 1;
    }
    counts
}

