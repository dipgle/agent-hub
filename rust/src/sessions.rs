/// KHÔNG làm hết cả lớp: đo cùng lúc, `projects-fd` và `merge xem init-project`
/// đều mang `AI/codetrail`.
pub fn label_sessions(rows: &mut [LiveSession], root: &Path) {
    let base: Vec<String> = rows
        .iter()
        .map(|s| {
            let f = s.folder.trim_matches('/');
            if f.is_empty() {
                s.name.clone()
            } else {
                format!("[{}]", strip_drawer(root, f))
            }
        })
        .collect();
    for (i, row) in rows.iter_mut().enumerate() {
        let clashes = base
            .iter()
            .enumerate()
            .any(|(j, b)| j != i && *b == base[i]);
        row.label = if clashes {
            let short = row.session_id.split('-').next().unwrap_or(&row.session_id);
            format!("{}·{short}", base[i])
        } else {
            base[i].clone()
        };
    }
}

/// Nhãn để hiện, cho những chỗ cầm một hàng RỜI khỏi ảnh chụp.
///
