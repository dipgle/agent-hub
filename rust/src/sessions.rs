/// Where a live session is hosted, decided by the process behind its pid.
///
/// `claude agents` says "interactive" for a terminal window and for a session
/// the VS Code / Cursor extension is running — the extension ships its own
/// `claude` binary under `~/.vscode/extensions/…`, so the command PATH is what
/// separates them, not the process name. A pid that answers nothing at all is
/// a row the CLI still lists for a process that is gone: `"dead"`, so the phone
/// can show it as something to clean up rather than as work in progress.
/// `(host, tty)` — tty đi kèm vì đó là chìa ghép phiên với cửa sổ Terminal
/// (`keys::window_of`). Tính rồi vứt đi thì mỗi lần cần lại phải gọi `ps` lần
/// nữa, trên đúng con số vừa đọc xong.
fn host_of(pid: i64, kind: &str) -> (String, String) {
    if pid <= 0 {
        // Background rows come back with pid 0 once stopped; `claude agents`
        // keeps listing them. Both dead rows seen on 2026-08-09 were exactly
        // this — stopped on 08-07, still on the list two days later.
        return ("dead".into(), String::new());
    }
    let out = run(
        "ps",
        &["-p", &pid.to_string(), "-o", "tty=,command="],
        RunOpts {
            timeout: Some(Duration::from_secs(5)),
            ..Default::default()
        },
    );
    let cmd = match out {
        Ok(r) if r.code == Some(0) => r.stdout,
        // `ps` exits non-zero when the pid is gone — that is the answer, not a
        // failure. A spawn error is different: say "unknown" rather than
        // claiming a session is dead on the strength of a broken probe.
        Ok(_) => return ("dead".into(), String::new()),
        Err(e) => {
            logging::warn(
                "session_host_probe_failed",
                json!({ "pid": pid, "err": e.to_string() }),
            );
            return ("unknown".into(), String::new());
        }
    };
    // `ps -o tty=,command=` in ra tty rồi mới tới dòng lệnh; tty là từ đầu tiên.
    let (tty, cmd) = match cmd.trim_start().split_once(char::is_whitespace) {
        Some((t, rest)) => (t, rest),
        None => ("??", cmd.as_str()),
    };
    (classify_host(cmd, kind, tty).to_string(), tty.to_string())
}

/// The half of `host_of` that is a decision rather than a probe.
///
/// Split out so it can be tested: the editor branch is the one the phone acts
/// on — those rows are hidden — and on a machine with no editor session open
/// there is no way to exercise it through the UI. `host_of` still owns the
/// `ps` call and the pid-is-gone answer; this owns only "given this command
/// line, whose session is it".
pub fn classify_host(cmd: &str, kind: &str, tty: &str) -> &'static str {
    // A background session hub started is `--bg`, never an editor's, whatever
    // binary is on the path — the kind is the stronger signal, so it wins.
    if kind == "background" {
        return "background";
    }
    // The extension ships its own `claude` under the editor's extension dir, so
    // the PATH is what separates it from a terminal — the process name is
    // `claude` in both cases.
    if cmd.contains("/.vscode") || cmd.contains("/.cursor") || cmd.contains("Cursor.app") {
        return "editor";
    }
    // "terminal" phải CÓ NGHĨA LÀ terminal.
    //
    // Hà hỏi 2026-08-09: *"danh sách phiên thực sự đang liệt kê terminal hay chỉ
    // claude?"* — và trước câu hỏi ấy, nhãn này được suy bằng LOẠI TRỪ: không
    // phải editor thì gọi là terminal. Một `claude` do script/cron/tiến trình
    // khác chạy (không gắn cửa sổ nào) vẫn đọc là "terminal", tức màn hình khai
    // một thứ nó chưa từng kiểm. Đo lúc sửa: cả 5 dòng đang có tty thật và khác
    // nhau (ttys000/003/005/006/010), nên nhãn *đang* đúng — nhưng đúng vì may,
    // không vì có ai kiểm.
    //
    // `ps` in `??` (hoặc `-`) khi tiến trình không có tty điều khiển.
    if tty.is_empty() || tty == "??" || tty == "-" {
        "detached"
    } else {
        "terminal"
    }
}

/// Hits that must suppress a preview, or empty if it is safe to carry.
pub fn preview_risk(text: &str) -> Vec<String> {
    crate::redaction::leak_scan(text, &[])
        .into_iter()
        .filter(|l| SECRET_LABELS.contains(&l.as_str()))
        .collect()
}

#[derive(Debug, Default, PartialEq)]
pub struct TranscriptTail {
    pub last_role: Option<String>,
    pub last_text: Option<String>,
    /// Timestamp carried by the last conversational record, if it has one.
    pub last_ts: Option<String>,
    /// Newest `permission-mode` seen in the window.
    pub permission_mode: Option<String>,
    /// Cỡ NGỮ CẢNH của lượt gần nhất, tính bằng token.
    ///
    /// `cache_read_input_tokens + cache_creation_input_tokens + input_tokens`
    /// của bản ghi `usage` cuối cùng chính là số token model vừa phải đọc để
    /// trả lời — tức là toàn bộ hội thoại đang mang theo. Đây là con số quyết
    /// định khi nào nên đóng sổ: phiên đầy ngữ cảnh thì mỗi lượt sau vừa chậm
    /// vừa tốn, và tới ngưỡng thì tự nén, mất chi tiết.
    ///
    /// KHÔNG suy ra được "còn bao nhiêu hạn mức" từ đây — đó là con số phía
    /// Anthropic giữ, CLI không có lệnh nào hỏi (đã tra `claude --help`
    /// 2026-08-09: `usage` là lệnh trong REPL, không phải lệnh dòng lệnh).
    pub context_tokens: u64,
    /// Model của lượt gần nhất, để biết cửa sổ ngữ cảnh rộng bao nhiêu.
    pub model: Option<String>,
    /// Subagent calls in this window that have no result yet.
    ///
    /// Hà 2026-08-09: *"một phiên đang chạy subagents thì cũng hiển thị được"*.
    /// A session that farmed its work out to subagents looks IDLE from the
    /// outside — the last conversational turn was minutes ago and nothing new
    /// lands until the subagents come back. Counting `Agent` calls whose
    /// `tool_use_id` never got a `tool_result` is the difference between "đang
    /// chạy" and "đứng im", and it is the one thing a phone cannot guess.
    pub pending_subagents: usize,
}

/// Subagent calls still waiting for their answer, inside this tail window.
///
/// Matched by `tool_use_id`, not by counting names: a session can fan out five
/// subagents and get three back, and "5 đang chạy" would be wrong in exactly
/// the situation the number exists for. Anything whose result fell outside the
/// 256KB window counts as finished — better to under-report than to leave a
/// phantom subagent running on the screen forever.
/// Ngữ cảnh của lượt gần nhất + model của nó.
///
/// Đọc XUÔI và giữ cái cuối cùng thấy được: bản ghi mới nhất là bản ghi đúng.
fn last_usage(tail: &str) -> (u64, Option<String>) {
    let mut ctx = 0u64;
    let mut model = None;
    for line in tail.lines() {
        let Ok(record) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        let Some(msg) = record.get("message") else {
            continue;
        };
        let Some(u) = msg.get("usage") else {
            continue;
        };
        let n = |k: &str| u.get(k).and_then(|v| v.as_u64()).unwrap_or(0);
        // Ba khoản cộng lại mới là cỡ ngữ cảnh thật: phần đọc từ cache là phần
        // lớn nhất và cũng là phần dễ quên nhất.
        ctx = n("input_tokens") + n("cache_read_input_tokens") + n("cache_creation_input_tokens");
        model = msg
            .get("model")
            .and_then(|m| m.as_str())
            .map(str::to_string)
            .or(model);
    }
    (ctx, model)
}

fn pending_subagents(tail: &str) -> usize {
    use std::collections::HashSet;
    let mut started: Vec<String> = Vec::new();
    let mut finished: HashSet<String> = HashSet::new();
    for line in tail.lines() {
        let Ok(record) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        let Some(blocks) = record
            .get("message")
            .and_then(|m| m.get("content"))
            .and_then(|c| c.as_array())
        else {
            continue;
        };
        for b in blocks {
            match b.get("type").and_then(|t| t.as_str()) {
                Some("tool_use") => {
                    let name = b.get("name").and_then(|n| n.as_str()).unwrap_or("");
                    if name == "Agent" || name == "Task" {
                        if let Some(id) = b.get("id").and_then(|i| i.as_str()) {
                            started.push(id.to_string());
                        }
                    }
                }
                Some("tool_result") => {
                    if let Some(id) = b.get("tool_use_id").and_then(|i| i.as_str()) {
                        finished.insert(id.to_string());
                    }
                }
                _ => {}
            }
        }
    }
    started.iter().filter(|id| !finished.contains(*id)).count()
}

/// Walk the tail backwards to the newest real conversation turn.
pub fn parse_tail(tail: &str) -> TranscriptTail {
    let (context_tokens, model) = last_usage(tail);
    let mut out = TranscriptTail {
        pending_subagents: pending_subagents(tail),
        context_tokens,
        model,
        ..Default::default()
    };
    for line in tail.lines().rev() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let Ok(record) = serde_json::from_str::<Value>(line) else {
            // A partial first line is expected: the tail starts mid-file.
            continue;
        };
        let kind = record.get("type").and_then(|t| t.as_str()).unwrap_or("");
        if kind == "permission-mode" && out.permission_mode.is_none() {
            out.permission_mode = record
                .get("permissionMode")
                .and_then(|m| m.as_str())
                .map(str::to_string);
        }
        if !is_conversation(kind) {
            continue;
        }
        // Newest wins: keep scanning backwards only for what is still missing,
        // never overwrite a turn already found with an older one.
        if out.last_text.is_some() {
            continue;
        }
        out.last_role = record
            .get("message")
            .and_then(|m| m.get("role"))
            .and_then(|r| r.as_str())
            .map(str::to_string)
            .or_else(|| Some(kind.to_string()));
        out.last_text = text_of(&record).map(|t| truncate(&t, PREVIEW_CHARS));
        out.last_ts = record
            .get("timestamp")
            .and_then(|t| t.as_str())
            .map(str::to_string);
        // Stop once BOTH are known: the newest turn and the mode it runs under.
        if out.last_text.is_some() && out.permission_mode.is_some() {
            break;
        }
    }
    out
}

fn read_tail(path: &Path) -> Result<String> {
    let mut file = std::fs::File::open(path)?;
    let len = file.metadata()?.len();
    if len > TAIL_BYTES {
        file.seek(SeekFrom::Start(len - TAIL_BYTES))?;
    }
    let mut buf = Vec::with_capacity(TAIL_BYTES as usize);
    file.read_to_end(&mut buf)?;
    Ok(String::from_utf8_lossy(&buf).to_string())
}

fn mtime_rfc3339(path: &Path) -> Option<String> {
    let modified = std::fs::metadata(path).ok()?.modified().ok()?;
    let ts: chrono::DateTime<chrono::Utc> = modified.into();
    Some(ts.to_rfc3339_opts(chrono::SecondsFormat::Secs, true))
}

/// Ask one account's CLI what it has running.
fn list_account(account: &ClaudeAccountCfg, cli: &str) -> Result<Vec<Value>> {
    // Absent variable = default account. Setting it to ~/.claude reports "not
    // logged in", so the default account MUST clear it, not point at it.
    let env = vec![(
        "CLAUDE_CONFIG_DIR".to_string(),
        account
            .config_dir
            .as_deref()
            .filter(|d| !d.is_empty())
            .map(|d| {
                crate::config::expand_home(Path::new(d))
                    .to_string_lossy()
                    .to_string()
            }),
    )];
    let out = run(
        cli,
        &["agents", "--json"],
        RunOpts {
            timeout: Some(LIST_TIMEOUT),
            env,
            ..Default::default()
        },
    )?;
    if out.timed_out {
        anyhow::bail!("`{cli} agents --json` timed out after {}ms", out.ms);
    }
    if out.code != Some(0) {
        anyhow::bail!(
            "`{cli} agents --json` exit {:?}: {}",
            out.code,
            truncate(
                if out.stderr.trim().is_empty() {
                    &out.stdout
                } else {
                    &out.stderr
                },
                200
            )
        );
    }
    let value: Value = serde_json::from_str(&out.stdout).map_err(|e| {
        anyhow::anyhow!("unparseable JSON: {e}; head={}", truncate(&out.stdout, 200))
    })?;
    Ok(value.as_array().cloned().unwrap_or_default())
}

/// Every process on the machine as `pid -> ppid`, in one `ps` call.
///
/// One call, not one per session: walking a parent chain with a `ps` per hop
/// costs a process spawn per hop and — worse — reads a tree that is moving
/// while it is read, so a chain could point at a pid that has already been
/// recycled.
fn parent_map() -> std::collections::HashMap<i64, i64> {
    let mut map = std::collections::HashMap::new();
    let out = run(
        "ps",
        &["-eo", "pid=,ppid="],
        RunOpts {
            timeout: Some(Duration::from_secs(10)),
            ..Default::default()
        },
    );
    match out {
        Ok(r) if r.code == Some(0) => {
            for line in r.stdout.lines() {
                let mut it = line.split_whitespace();
                if let (Some(pid), Some(ppid)) = (it.next(), it.next()) {
                    if let (Ok(pid), Ok(ppid)) = (pid.parse::<i64>(), ppid.parse::<i64>()) {
                        map.insert(pid, ppid);
                    }
                }
            }
        }
        Ok(r) => logging::warn("ps_tree_failed", json!({ "code": r.code })),
        Err(e) => logging::warn("ps_tree_failed", json!({ "err": e.to_string() })),
    }
    map
}

/// Which listed session spawned each windowless one.
///
/// Only rows with no window need this — a terminal session's origin is the
/// window it sits in. Depth is capped: a cycle in the table (or a pid recycled
/// between the two reads) must not spin forever.
fn link_parents(rows: &mut [LiveSession]) {
    let needs = rows
        .iter()
        .any(|r| matches!(r.host.as_str(), "background" | "detached"));
    if !needs {
        return;
    }
    let tree = parent_map();
    let by_pid: std::collections::HashMap<i64, (String, String)> = rows
        .iter()
        .filter(|r| r.pid > 0)
        .map(|r| (r.pid, (r.session_id.clone(), r.name.clone())))
        .collect();

    for row in rows.iter_mut() {
        if !matches!(row.host.as_str(), "background" | "detached") || row.pid <= 0 {
            continue;
        }
        let mut pid = row.pid;
        for _ in 0..12 {
            let Some(&ppid) = tree.get(&pid) else { break };
            if ppid <= 1 {
                break;
            }
            if let Some((id, name)) = by_pid.get(&ppid) {
                if *id != row.session_id {
                    row.parent_session_id = Some(id.clone());
                    row.parent_name = Some(name.clone());
                    break;
                }
            }
            pid = ppid;
        }
    }
}

/// Every live session across every configured account, newest activity first.
pub fn snapshot(cfg: &Config) -> SessionsSnapshot {
    let mut out = SessionsSnapshot::default();
    let root = cfg.claude_transcript_root();
    let mut hidden_editor = 0usize;

    for account in &cfg.claude_accounts_or_ambient() {
        let raw = match list_account(account, &cfg.claude_cli) {
            Ok(v) => v,
            Err(e) => {
                // An account that failed to answer is NOT an account with zero
                // sessions, and the difference matters on a phone.
                logging::warn(
                    "claude_agents_list_failed",
                    json!({ "account": account.name, "err": e.to_string() }),
                );
                out.notes.push(format!(
                    "{}: {}",
                    account.name,
                    truncate(&e.to_string(), 200)
                ));
                continue;
            }
        };

        for s in raw {
            let cwd = s
                .get("cwd")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .to_string();
            let session_id = s
                .get("sessionId")
                .and_then(|v| v.as_str())
                .unwrap_or_default()
                .to_string();
            let mut row = LiveSession {
                account: account.name.clone(),
                name: s
                    .get("name")
                    .and_then(|v| v.as_str())
                    .unwrap_or("(không tên)")
                    .to_string(),
                kind: s
                    .get("kind")
                    .and_then(|v| v.as_str())
                    .unwrap_or("unknown")
                    .to_string(),
                host: String::new(), // set below, once `kind` and `pid` are read
                pid: s.get("pid").and_then(|v| v.as_i64()).unwrap_or(0),
                started_at_ms: s.get("startedAt").and_then(|v| v.as_i64()).unwrap_or(0),
                status: s.get("status").and_then(|v| v.as_str()).map(str::to_string),
                state: s.get("state").and_then(|v| v.as_str()).map(str::to_string),
                last_activity: None,
                last_role: None,
                last_text: None,
                note: None,
                permission_mode: None,
                cwd: cwd.clone(),
                session_id: session_id.clone(),
                // Điền ở tầng có `Db` (`pipeline::mark_started_by_hub`); ở đây
                // không có sổ để tra, mà đoán thì thà để trống.
                started_by_hub: false,
                tty: String::new(),
                pending_subagents: 0,
                context_tokens: 0,
                model: None,
                // Điền sau khi đã có đủ mọi hàng: quan hệ cha-con chỉ tra được
                // khi biết pid của TẤT CẢ các phiên.
                parent_session_id: None,
                parent_name: None,
            };

            let (host, tty) = host_of(row.pid, &row.kind);
            row.host = host;
            row.tty = tty;

            // Phiên do extension VS Code/Cursor chạy KHÔNG lên màn.
            //
            // Hà chốt 2026-08-09: *"bỏ các phiên của editor đi, có quản lý được
            // tin nhắn của nó đâu"*. Đúng phần cốt lõi — trên máy này 8/13 dòng
            // là phiên editor, chúng đẩy 3 cửa sổ terminal (thứ Hà thực sự theo)
            // xuống dưới màn, và `/stop` không dừng được chúng.
            //
            // Ghi rõ chỗ chưa đúng hẳn, để đừng ai coi đây là "không làm gì
            // được với phiên editor": `/ask` và `/handover` CHẠY được trên
            // chúng — nghiệm thu tối 08-08 fork chính phiên editor `projects-cd`
            // và trả lời đúng ngữ cảnh. Đây là lựa chọn về MÀN HÌNH (bớt nhiễu),
            // không phải giới hạn kỹ thuật. Bỏ dòng dưới là chúng hiện lại ngay.
            //
            // Đếm rồi log, không lặng lẽ nuốt: một danh sách ngắn đi mà không ai
            // biết vì sao là danh sách nói dối.
            if row.host == "editor" {
                hidden_editor += 1;
                continue;
            }

            if row.host == "dead" {
                // Never silently: the row stays visible (a stuck session is
                // something to clean up), but it must not read as live work.
                row.note = Some(
                    "không còn tiến trình — phiên đã dừng, `claude agents` vẫn liệt kê".into(),
                );
            }

            if session_id.is_empty() {
                row.note = Some("phiên không có sessionId".into());
                out.sessions.push(row);
                continue;
            }

            let path = transcript_path(&root, &cwd, &session_id);
            if !path.exists() {
                // Seen for real: 1 of 14 sessions had no transcript yet.
                row.note = Some("chưa có nhật ký phiên".into());
                out.sessions.push(row);
                continue;
            }
            row.last_activity = mtime_rfc3339(&path);
            match read_tail(&path) {
                Ok(tail) => {
                    let parsed = parse_tail(&tail);
                    if parsed.last_text.is_none() {
                        row.note = Some("chưa có lượt hội thoại nào đọc được".into());
                    }
                    if let Some(ts) = parsed.last_ts {
                        row.last_activity = Some(ts);
                    }
                    row.permission_mode = parsed.permission_mode.clone();
                    row.pending_subagents = parsed.pending_subagents;
                    row.context_tokens = parsed.context_tokens;
                    row.model = parsed.model.clone();
                    row.last_role = parsed.last_role;
                    // Suppressed HERE, at the source, so no downstream surface
                    // can forget: the snapshot, the portal doc and the phone
                    // all read this struct.
                    row.last_text = match &parsed.last_text {
                        Some(t) => {
                            let risk = preview_risk(t);
                            if risk.is_empty() {
                                parsed.last_text.clone()
                            } else {
                                row.note = Some(format!(
                                    "ẩn phần xem trước: có thể chứa bí mật ({}) — mở phiên trên máy để xem",
                                    risk.join(", ")
                                ));
                                None
                            }
                        }
                        None => None,
                    };
                }
                Err(e) => {
                    logging::warn(
                        "claude_transcript_read_failed",
                        json!({ "path": path.display().to_string(), "err": e.to_string() }),
                    );
                    row.note = Some(format!(
                        "không đọc được nhật ký: {}",
                        truncate(&e.to_string(), 120)
                    ));
                }
            }
            out.sessions.push(row);
        }
    }

    link_parents(&mut out.sessions);
    out.hidden_editor = hidden_editor;
    if hidden_editor > 0 {
        logging::info(
            "sessions_editor_hidden",
            json!({ "count": hidden_editor, "why": "editor-hosted sessions are not shown on the phone" }),
        );
    }

    // Newest first: half the live sessions had not moved in 40 hours, so a flat
    // list buries the one being worked on right now.
    out.sessions.sort_by(|a, b| {
        b.last_activity
            .cmp(&a.last_activity)
            .then_with(|| b.started_at_ms.cmp(&a.started_at_ms))
    });
    out
}

/// One thing that happened in a session, in the order it happened.
///
/// This is the unit the phone renders to look like a terminal: a sentence, a
/// command, a command's output, a thought. `kind` is what it was, `text` is
/// what to show, `detail` is the extra line a command needs (its arguments).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct StreamEvent {
    /// "say" · "tool" · "result" · "think"
    pub kind: String,
    /// "user" | "assistant"
    pub role: String,
    pub ts: Option<String>,
    /// Tool name for `tool`, empty otherwise.
    pub name: String,
    pub text: String,
    /// True when the leak gate replaced the text — never a silent blank.
    pub withheld: bool,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct SessionStream {
    /// Chữ đang hiện trên cửa sổ terminal của phiên, đã gác bí mật.
    ///
    /// Khác `events` ở chỗ căn bản: `events` đọc từ NHẬT KÝ, chỉ có sau khi một
    /// lượt kết thúc. Màn hình là thứ đang hiện NGAY BÂY GIỜ — kể cả hộp chọn
    /// đang chờ, thanh tiến trình, dòng lỗi vừa in. Một phiên dừng lại hỏi thì
    /// nhật ký đứng yên và chỉ trường này nói ra được.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub screen: Option<String>,
    /// Các lựa chọn nhận ra trên màn, nếu phiên đang hỏi.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub choices: Vec<serde_json::Value>,
    pub session_id: String,
    pub events: Vec<StreamEvent>,
    /// Events dropped off the front because the window is bounded.
    pub older_hidden: usize,
    pub note: Option<String>,
}

/// How much of a tool's output to carry. A `Bash` result can be a whole test
/// run; the phone needs the shape of it, not all of it.
const RESULT_CHARS: usize = 700;
const SAY_CHARS: usize = 4000;

fn block_text(block: &Value) -> String {
    match block.get("type").and_then(|t| t.as_str()) {
        Some("text") => block
            .get("text")
            .and_then(|t| t.as_str())
            .unwrap_or_default()
            .to_string(),
        Some("thinking") => block
            .get("thinking")
            .and_then(|t| t.as_str())
            .unwrap_or_default()
            .to_string(),
        Some("tool_use") => {
            let input = block
                .get("input")
                .map(|i| i.to_string())
                .unwrap_or_default();
            input
        }
        Some("tool_result") => match block.get("content") {
            Some(Value::String(s)) => s.clone(),
            Some(Value::Array(items)) => items
                .iter()
                .filter_map(|b| b.get("text").and_then(|t| t.as_str()))
                .collect::<Vec<_>>()
                .join("\n"),
            _ => String::new(),
        },
        _ => String::new(),
    }
}

/// Every block becomes an event, and every event passes the leak gate on its
/// OWN text.
///
/// This is where "show it like the terminal" collides with "do not publish
/// secrets": a `tool_result` is the output of a command, which is exactly
/// where keys and env vars surface. Gating only the last turn (what the list
/// screen does) would be useless here.
pub fn parse_stream(tail: &str, limit: usize) -> SessionStream {
    let mut events: Vec<StreamEvent> = vec![];
    for line in tail.lines() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        // The window starts mid-file, so a partial first line is expected.
        let Ok(record) = serde_json::from_str::<Value>(line) else {
            continue;
        };
        let kind = record.get("type").and_then(|t| t.as_str()).unwrap_or("");
        if !is_conversation(kind) {
            continue;
        }
        let ts = record
            .get("timestamp")
            .and_then(|t| t.as_str())
            .map(str::to_string);
        let role = record
            .get("message")
            .and_then(|m| m.get("role"))
            .and_then(|r| r.as_str())
            .unwrap_or(kind)
            .to_string();
        let Some(content) = record.get("message").and_then(|m| m.get("content")) else {
            continue;
        };

        let blocks: Vec<Value> = match content {
            Value::String(s) => vec![json!({ "type": "text", "text": s })],
            Value::Array(a) => a.clone(),
            _ => vec![],
        };

        for block in blocks {
            let (event_kind, name, cap) = match block.get("type").and_then(|t| t.as_str()) {
                Some("text") => ("say", String::new(), SAY_CHARS),
                Some("thinking") => ("think", String::new(), RESULT_CHARS),
                Some("tool_use") => (
                    "tool",
                    block
                        .get("name")
                        .and_then(|n| n.as_str())
                        .unwrap_or("?")
                        .to_string(),
                    RESULT_CHARS,
                ),
                Some("tool_result") => ("result", String::new(), RESULT_CHARS),
                _ => continue,
            };
            let raw = block_text(&block);
            let raw = raw.trim();
            if raw.is_empty() {
                continue;
            }
            let risk = preview_risk(raw);
            events.push(StreamEvent {
                kind: event_kind.to_string(),
                role: role.clone(),
                ts: ts.clone(),
                name,
                text: if risk.is_empty() {
                    truncate(raw, cap)
                } else {
                    format!("[hub ẩn: có thể chứa bí mật ({})]", risk.join(", "))
                },
                withheld: !risk.is_empty(),
            });
        }
    }

    let older_hidden = events.len().saturating_sub(limit);
    if older_hidden > 0 {
        events.drain(..older_hidden);
    }
    SessionStream {
        session_id: String::new(),
        events,
        older_hidden,
        note: None,
        // Màn hình do `portal` gắn vào (nó biết `tty`); ở đây chỉ có nhật ký.
        screen: None,
        choices: Vec::new(),
    }
}

/// Find a session's transcript without knowing its `cwd`.
///
/// The follow loop only has an id: it must not pay for three `claude agents`
/// calls every couple of seconds just to rebuild a path. Transcript folders are
/// shallow, so one readdir per project folder is cheap — and this also survives
/// a session whose `cwd` the caller got wrong.
pub fn find_transcript(root: &Path, session_id: &str) -> Option<PathBuf> {
    let file = format!("{session_id}.jsonl");
    let projects = root.join("projects");
    let dirs = std::fs::read_dir(&projects).ok()?;
    for entry in dirs.flatten() {
        let candidate = entry.path().join(&file);
        if candidate.exists() {
            return Some(candidate);
        }
    }
    None
}

/// When the transcript last changed — the signal the follow loop watches.
pub fn transcript_mtime(path: &Path) -> Option<std::time::SystemTime> {
    std::fs::metadata(path).ok()?.modified().ok()
}

/// The recent stream of one session, ready to render.
pub fn stream(cfg: &Config, session_id: &str, cwd: &str, limit: usize) -> SessionStream {
    let mut out = SessionStream {
        session_id: session_id.to_string(),
        ..Default::default()
    };
    let root = cfg.claude_transcript_root();
    let by_cwd = transcript_path(&root, cwd, session_id);
    let path = if by_cwd.exists() {
        by_cwd
    } else {
        match find_transcript(&root, session_id) {
            Some(p) => p,
            None => {
                out.note = Some("chưa có nhật ký phiên".into());
                return out;
            }
        }
    };
    match read_tail(&path) {
        Ok(tail) => {
            let parsed = parse_stream(&tail, limit);
            out.events = parsed.events;
            out.older_hidden = parsed.older_hidden;
            if out.events.is_empty() {
                out.note = Some("chưa có lượt hội thoại nào đọc được".into());
            }
        }
        Err(e) => {
            logging::warn(
                "claude_transcript_read_failed",
                json!({ "path": path.display().to_string(), "err": e.to_string() }),
            );
            out.note = Some(format!(
                "không đọc được nhật ký: {}",
                truncate(&e.to_string(), 120)
            ));
        }
    }
    out
}

