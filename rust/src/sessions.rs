/// How much of the tail of a transcript to read. Transcripts reach 12 MB; the
/// last conversational turn is always within a few hundred KB of the end, and
/// reading the whole file 14 times per cycle would be the expensive way to
/// learn the same thing.
const TAIL_BYTES: u64 = 256 * 1024;
const PREVIEW_CHARS: usize = 240;
const LIST_TIMEOUT: Duration = Duration::from_secs(30);

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct LiveSession {
    /// Which account owns it — the label from config, not a credential.
    pub account: String,
    pub session_id: String,
    /// Autogenerated ("projects-87") or meaningful ("Tiếp tục dwork").
    pub name: String,
    pub cwd: String,
    /// "interactive" (a terminal / editor) or "background".
    pub kind: String,
    /// WHERE the session actually lives: `"terminal"` (has a controlling tty),
    /// `"editor"` (the VS Code / Cursor extension), `"background"`, `"detached"`
    /// (a live process with no tty and no editor path — a script, a cron, or
    /// something hub did not start), or `"dead"` when no process is behind it
    /// any more.
    ///
    /// `kind` alone reads "interactive" for a terminal window and for an
    /// editor-hosted session alike, and on 2026-08-09 that cost a real
    /// question: the phone said 13 sessions while the owner had 3 terminals
    /// open. He was right and so was hub — 3 terminals, 8 sessions inside VS
    /// Code, 2 dead rows the CLI still reports. A screen that cannot tell those
    /// apart is a screen that gets argued with instead of read.
    pub host: String,
    pub pid: i64,
    pub started_at_ms: i64,
    /// Last write to the transcript, RFC3339. `None` = no transcript found.
    pub last_activity: Option<String>,
    /// Role of the last real conversation turn, skipping bookkeeping records.
    pub last_role: Option<String>,
    pub last_text: Option<String>,
    /// Why this row is thinner than the others. Never silently empty.
    pub note: Option<String>,
    /// Whether the agent is working right now ("busy") or waiting ("idle"), and
    /// whether it finished ("done"). Both come straight from `claude agents`,
    /// and both are **absent for interactive sessions** — measured 2026-08-08,
    /// only background rows carry them. An empty pair therefore means "hub
    /// cannot tell", never "the session is idle".
    ///
    /// It is also the only honest answer hub has to "is it still working?":
    /// the transcript records neither a cost nor a completion marker.
    pub status: Option<String>,
    pub state: Option<String>,
    /// The permission mode the session is running under ("auto", "dontAsk",
    /// "default"…).
    ///
    /// Measured 2026-08-08 across ~14k records: the transcript records the
    /// MODE and never an individual pending prompt, and every session here runs
    /// `auto` (648) or `dontAsk` (76) — they do not ask. So "show me when it
    /// asks for permission" has nothing to show; what matters on a phone is
    /// knowing a session is running unattended in the first place.
    pub permission_mode: Option<String>,
    /// True when THIS hub started the session (`/new` from the phone).
    ///
    /// `kind == "background"` only says "no window"; it cannot say who opened
    /// it — a `claude --bg` typed by hand looks identical. Hà asked for a label
    /// that says *ai tạo* (2026-08-09), and a badge that guessed would be worse
    /// than no badge, so hub keeps a list of the ids it started and this field
    /// is filled from that list (`pipeline::mark_started_by_hub`). Never
    /// inferred.
    #[serde(default)]
    pub started_by_hub: bool,
    /// Subagent đang chạy (xem `TranscriptTail::pending_subagents`).
    #[serde(default)]
    pub pending_subagents: usize,
    /// tty của tiến trình, hoặc rỗng. Chìa để tìm cửa sổ Terminal của phiên.
    #[serde(default)]
    pub tty: String,
    /// Cỡ ngữ cảnh lượt gần nhất, và model để biết cửa sổ rộng bao nhiêu.
    #[serde(default)]
    pub context_tokens: u64,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub model: Option<String>,
    /// The listed session whose process tree this one hangs off, if any.
    ///
    /// A background session has no window, so "where did this come from?" has
    /// no answer on screen — but the OS knows: walking `ppid` from a background
    /// row lands on the `claude` that spawned it. Measured 2026-08-09, both
    /// background sessions on this machine resolved in 3-4 hops to a session
    /// already in the list (`Tiếp tục dwork` → `claude tiếp dwork` on ttys003;
    /// `Tự chạy lại khi gặp lỗi` → `claude tiếp tfl5` on ttys006).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent_session_id: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent_name: Option<String>,
}

